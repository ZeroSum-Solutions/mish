const MOTIONSITES_FOLDER_RULE_ID = "motionsites-plugin-folder";

/**
 * Fixture roots exempt from path and shape rules (never from the blob rule).
 * Anchored at known roots, not any depth, so a nested copy of the folder name
 * cannot hide content. Add a root here when a package gains such fixtures.
 */
export const LICENSED_PACK_FIXTURE_ROOTS = ["apps/daemon/tests/fixtures/licensed-pack/"] as const;

export function isLicensedPackFixturePath(repositoryPath: string): boolean {
  return LICENSED_PACK_FIXTURE_ROOTS.some((root) => repositoryPath.startsWith(root));
}

// ── Archive rule ─────────────────────────────────────────────────────────

const TRACKED_ARCHIVE_RULE_ID = "tracked-archive";
const ARCHIVE_SUFFIX = /\.(?:tgz|tar|tar\.gz|zip)$/i;

/**
 * Legitimate tracked archives that are not pack-shaped, by exact path, each
 * with a comment saying what it is. Empty: the tree held no tracked archive
 * when the rule was added (2026-10-08).
 */
export const LICENSED_PACK_ARCHIVE_ALLOWLIST: readonly string[] = [];

/** A tracked archive the archive rule flags: outside the fixture roots and not allowlisted. */
export function isForbiddenTrackedArchive(repositoryPath: string): boolean {
  return (
    ARCHIVE_SUFFIX.test(repositoryPath) &&
    !isLicensedPackFixturePath(repositoryPath) &&
    !LICENSED_PACK_ARCHIVE_ALLOWLIST.includes(repositoryPath)
  );
}

function matchesPathRule(rule: PathRule, repositoryPath: string): boolean {
  return (
    (rule.exact?.includes(repositoryPath) ?? false) ||
    (rule.prefixes?.some((prefix) => repositoryPath.startsWith(prefix)) ?? false)
  );
}

// ── Shape rules ──────────────────────────────────────────────────────────

// Never read for shape rules: formats with no text to match.
const BINARY_EXTENSIONS = new Set([
  ".png", ".jpg", ".jpeg", ".gif", ".webp", ".avif", ".ico", ".icns", ".bmp", ".tif", ".tiff",
  ".mp4", ".webm", ".mov", ".m4v", ".mp3", ".wav", ".ogg", ".m4a", ".flac",
  ".woff", ".woff2", ".ttf", ".otf", ".eot",
  ".zip", ".tgz", ".pdf", ".wasm", ".node", ".dmg", ".exe", ".sqlite", ".db",
]);

const CULT_REGISTRY_AUTHOR = /"author"\s*:\s*"Cult Pro"/;
const ADAPTER_SOURCE_SHA = /\bsourceSha256["']?\s*:\s*["'][0-9a-f]{64}["']/;
const ADAPTER_CULT_ID = /\b(?:id|sourceBlockId)["']?\s*:\s*["']cult:/;
// Built from parts so this file does not match its own rules.
const ADAPTER_DERIVED_HEADER = ["Derived at author time from the licensed", "Cult UI Pro", "block"].join(" ");
const MOTIONSITES_HOMEPAGE = /"homepage"\s*:\s*"https?:\/\/(?:www\.)?motionsites\.ai(?:[/"?#])/i;
/** MotionSites template authors; with a CC-BY-4.0 licence they mark a template manifest. */
export const MOTIONSITES_AUTHOR_NAMES: readonly string[] = ["Eli"];
const MOTIONSITES_LICENCE = "cc-by-4.0";
// Converted kit markup: the converter's scoped root rule in CSS, and its root
// element followed by its short utility classes in HTML.
const CONVERTED_CSS_ROOT = /\.cult-[a-z0-9-]+\{[^}]*?line-height:1\.5;font-family:var\(--role-font-body/;
const CONVERTED_HTML_ROOT = /<div class=\\?"cult-[a-z0-9-]+\\?" data-od-role=\\?"[a-z0-9-]+\\?">/;
const CONVERTED_HTML_UTILITIES = /class=\\?"c[0-9a-z]{1,3}(?: c[0-9a-z]{1,3})+\\?"/;
const GENUI_CULT_SEED_ROW = /"Source"\s*:\s*"Cult UI Pro"/;
const SECTION_CATALOG_CULT_PRO = /"sourceKind"\s*:\s*"cult-pro"/;
const PACK_MANIFEST_FORMAT = /"format"\s*:\s*"mishh-pack@1"/;

function hasLicensedGenuiRow(value: unknown): boolean {
  if (Array.isArray(value)) return value.some(hasLicensedGenuiRow);
  if (value === null || typeof value !== "object") return false;
  const record = value as Record<string, unknown>;
  const source = record.source;
  if (
    record.licenceDecision === "licensed" &&
    source !== null &&
    typeof source === "object" &&
    (source as Record<string, unknown>).name === "cult-ui-pro"
  ) {
    return true;
  }
  return Object.values(record).some(hasLicensedGenuiRow);
}

/** A plugin manifest that names the MotionSites homepage, or a MotionSites author under CC-BY-4.0. */
export function isMotionSitesManifestText(text: string): boolean {
  if (MOTIONSITES_HOMEPAGE.test(text)) return true;
  const lower = text.toLowerCase();
  if (!lower.includes(MOTIONSITES_LICENCE)) return false;
  let manifest: unknown;
  try {
    manifest = JSON.parse(text);
  } catch {
    return false;
  }
  if (manifest === null || typeof manifest !== "object") return false;
  const record = manifest as Record<string, unknown>;
  const author = record.author;
  const authorName =
    typeof author === "string"
      ? author
      : author !== null && typeof author === "object"
        ? (author as Record<string, unknown>).name
        : undefined;
  const licence = record.license ?? record.licence;
  return (
    typeof authorName === "string" &&
    MOTIONSITES_AUTHOR_NAMES.some((name) => name.toLowerCase() === authorName.trim().toLowerCase()) &&
    typeof licence === "string" &&
    licence.trim().toLowerCase() === MOTIONSITES_LICENCE
  );
}

function isShapeCandidate(repositoryPath: string): boolean {
  return !BINARY_EXTENSIONS.has(path.posix.extname(repositoryPath).toLowerCase());
}

function shapeReasons(repositoryPath: string, text: string, switches: LicensedPackRuleSwitches): string[] {
  const reasons: string[] = [];
  const isJson = /\.json(?:\.gz)?$/.test(repositoryPath);

  // Run on every text file, so a renamed or slightly edited copy still matches.
  if (CULT_REGISTRY_AUTHOR.test(text)) reasons.push("shape:cult-registry-author");
  if ((ADAPTER_SOURCE_SHA.test(text) && ADAPTER_CULT_ID.test(text)) || text.includes(ADAPTER_DERIVED_HEADER)) {
    reasons.push("shape:cult-adapter-signature");
  }
  if (CONVERTED_CSS_ROOT.test(text) || (CONVERTED_HTML_ROOT.test(text) && CONVERTED_HTML_UTILITIES.test(text))) {
    reasons.push("shape:cult-converted-markup");
  }
  if (isJson && isMotionSitesManifestText(text)) reasons.push("shape:motionsites-manifest");
  if (isJson && text.includes("cult-ui-pro") && text.includes("licensed")) {
    try {
      if (hasLicensedGenuiRow(JSON.parse(text))) reasons.push("shape:genui-cult-licensed-row");
    } catch {
      // Not parseable JSON: no catalog rows to inspect.
    }
  }
  if (isJson && GENUI_CULT_SEED_ROW.test(text)) reasons.push("shape:genui-cult-seed-row");
  if (isJson && switches.sectionCatalogCultProRule && SECTION_CATALOG_CULT_PRO.test(text)) {
    reasons.push("shape:section-catalog-cult-pro");
  }
  if (path.posix.basename(repositoryPath) === "pack.json" && PACK_MANIFEST_FORMAT.test(text)) {
    reasons.push("shape:pack-manifest");
  }
  return reasons;
}

// ── Matcher ──────────────────────────────────────────────────────────────

export type TrackedFile = { path: string; oid: string };

export type LicensedPackViolation = { path: string; reasons: string[] };

/** Resolves to the file's text, or undefined when it holds no text (binary). Throws when unreadable. */
export type ReadRepositoryText = (repositoryPath: string) => Promise<string | undefined>;

/**
 * Path-rule matches only (rule family 1), keyed by repository path. Shared by
 * the guard and the blob-list generator so both see the same licensed set.
 */
export async function findLicensedPackPathMatches(
  paths: readonly string[],
  readText: ReadRepositoryText,
  switches: LicensedPackRuleSwitches = LICENSED_PACK_RULE_SWITCHES,
): Promise<Map<string, string[]>> {
  const rules = LICENSED_PACK_PATH_RULES;

  // Every plugins/** folder whose manifest is a MotionSites manifest is
  // licensed as a whole, so a 19th example is caught without a name list.
  const motionSitesFolders: string[] = [];
  for (const repositoryPath of paths) {
    if (!repositoryPath.startsWith("plugins/") || path.posix.basename(repositoryPath) !== "open-design.json") continue;
    if (isLicensedPackFixturePath(repositoryPath)) continue;
    const text = await readText(repositoryPath);
    if (text !== undefined && isMotionSitesManifestText(text)) {
      motionSitesFolders.push(`${path.posix.dirname(repositoryPath)}/`);
    }
  }

  const matches = new Map<string, string[]>();
  for (const repositoryPath of paths) {
    if (isLicensedPackFixturePath(repositoryPath)) continue;
    const reasons = rules.filter((rule) => matchesPathRule(rule, repositoryPath)).map((rule) => `path:${rule.id}`);
    if (motionSitesFolders.some((folder) => repositoryPath.startsWith(folder))) {
      reasons.push(`path:${MOTIONSITES_FOLDER_RULE_ID}`);
    }
    if (reasons.length > 0) matches.set(repositoryPath, reasons);
  }
  return matches;
}

export async function findLicensedPackContentViolations(input: {
  files: readonly TrackedFile[];
  readText: ReadRepositoryText;
  deniedBlobs: ReadonlySet<string>;
  rules?: LicensedPackRuleSwitches;
}): Promise<LicensedPackViolation[]> {
  const switches = input.rules ?? LICENSED_PACK_RULE_SWITCHES;
  const pathMatches = await findLicensedPackPathMatches(
    input.files.map((file) => file.path),
    input.readText,
    switches,
  );

  const violations: LicensedPackViolation[] = [];
  for (const file of input.files) {
    const reasons = [...(pathMatches.get(file.path) ?? [])];
    if (isForbiddenTrackedArchive(file.path)) reasons.push(`path:${TRACKED_ARCHIVE_RULE_ID}`);
    if (input.deniedBlobs.has(file.oid)) reasons.push("blob");

    // A path match already settles a file, so skip the content read there.
    if (
      !pathMatches.has(file.path) &&
      !isLicensedPackFixturePath(file.path) &&
      isShapeCandidate(file.path)
    ) {
      const text = await input.readText(file.path);
      if (text !== undefined) reasons.push(...shapeReasons(file.path, text, switches));
    }

    if (reasons.length > 0) violations.push({ path: file.path, reasons });
  }
  return violations.sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0));
}

// ── Blob ids and the denylist file ───────────────────────────────────────

/** The id `git hash-object` gives these bytes (SHA-1 object format). */
export function gitBlobId(bytes: Uint8Array): string {
  return createHash("sha1").update(`blob ${bytes.byteLength}\0`).update(bytes).digest("hex");
}

const BLOB_ID = /^[0-9a-f]{40}$/;

export function parseLicensedPackBlobList(text: string): { ids: Set<string> } | { error: string } {
  const ids = new Set<string>();
  const lines = text.split("\n");
  for (const [index, line] of lines.entries()) {
    if (line === "" && index === lines.length - 1) continue;
    if (!BLOB_ID.test(line)) return { error: `line ${index + 1} is not a git blob id` };
    ids.add(line);
  }
  return { ids };
}

export function formatLicensedPackBlobList(ids: Iterable<string>): string {
  const sorted = [...new Set(ids)].sort();
  return sorted.length === 0 ? "" : `${sorted.join("\n")}\n`;
}

// ── Mode and reporting ───────────────────────────────────────────────────

export function resolveLicensedPackGuardMode(
  value: string | undefined,
): { mode: LicensedPackGuardMode } | { error: string } {
  if (value === undefined || value === "") return { mode: DEFAULT_LICENSED_PACK_GUARD_MODE };
  if (value === "warn" || value === "enforce") return { mode: value };
  return { error: `${LICENSED_PACK_GUARD_MODE_ENV} must be "warn" or "enforce", got ${JSON.stringify(value)}` };
}

type GuardLog = { error: (line: string) => void; log: (line: string) => void };

// Warn mode is permanent (P1-8 is cancelled; see the file header), so this
// reads as a plain advisory label, not a reference to a pending phase.
const ADVISORY_PREFIX = "advisory (on-demand check)";

/** Prints the violations and returns the check result for the mode. */
export function reportLicensedPackViolations(
  violations: readonly LicensedPackViolation[],
  mode: LicensedPackGuardMode,
  log: GuardLog = console,
): boolean {
  if (violations.length === 0) {
    log.log(`Licensed pack content check passed (${mode}): no licensed pack content in the tracked tree.`);
    return true;
  }
  if (mode === "warn") {
    log.error(
      `Licensed pack content (${ADVISORY_PREFIX}; ${LICENSED_PACK_GUARD_MODE_ENV}=enforce fails): ${violations.length} tracked file(s):`,
    );
    for (const violation of violations) {
      log.error(`- ${ADVISORY_PREFIX}: ${violation.path} [${violation.reasons.join(", ")}]`);
    }
    return true;
  }
  log.error(`Licensed pack content check failed: ${violations.length} tracked file(s) hold licensed pack content:`);
  for (const violation of violations) log.error(`- ${violation.path} [${violation.reasons.join(", ")}]`);
  return false;
}

// ── Guard entry ──────────────────────────────────────────────────────────

/**
 * Tracked blobs from the index (`git ls-files -s -z`). Gitlinks (submodules)
 * hold no blob in this repository and are returned separately for reporting.
 */
export async function listTrackedFiles(repoRoot: string): Promise<{ files: TrackedFile[]; gitlinks: string[] }> {
  const { stdout } = await execFileAsync("git", ["ls-files", "-s", "-z"], {
    cwd: repoRoot,
    encoding: "utf8",
    maxBuffer: 256 * 1024 * 1024,
  });
  const files: TrackedFile[] = [];
  const gitlinks: string[] = [];
  for (const record of stdout.split("\0")) {
    if (record === "") continue;
    const tab = record.indexOf("\t");
    const [mode, oid] = record.slice(0, tab).split(" ");
    const repositoryPath = record.slice(tab + 1);
    if (mode === "160000") gitlinks.push(repositoryPath);
    else if (oid !== undefined) files.push({ path: repositoryPath, oid });
  }
  return { files, gitlinks };
}

/** Text of a file for the shape rules: gzip is unpacked, and NUL bytes mean binary (undefined). */
export function decodeRepositoryText(repositoryPath: string, bytes: Buffer): string | undefined {
  let content = bytes;
  if (repositoryPath.endsWith(".gz")) {
    try {
      content = gunzipSync(bytes, { maxOutputLength: 64 * 1024 * 1024 });
    } catch {
      return undefined;
    }
  }
  return content.subarray(0, 8000).includes(0) ? undefined : content.toString("utf8");
}

export async function checkLicensedPackContent(
  context: { repoRoot: string },
  overrides: { mode?: string; blobListPath?: string; minBlobIds?: number } = {},
): Promise<boolean> {
  const resolved = resolveLicensedPackGuardMode(overrides.mode ?? process.env[LICENSED_PACK_GUARD_MODE_ENV]);
  if ("error" in resolved) {
    console.error(`Licensed pack content check failed: ${resolved.error}.`);
    return false;
  }
  const { mode } = resolved;
  // In warn mode a broken input is reported and passes; enforce fails closed.
  const setupProblem = (message: string): boolean => {
    console.error(
      mode === "warn"
        ? `Licensed pack content (${ADVISORY_PREFIX}): ${message}`
        : `Licensed pack content check failed: ${message}`,
    );
    return mode === "warn";
  };

  const blobListPath = overrides.blobListPath ?? LICENSED_PACK_BLOB_LIST_PATH;
  let deniedBlobs = new Set<string>();
  let blobListOk = true;
  try {
    const parsed = parseLicensedPackBlobList(await readFile(path.join(context.repoRoot, blobListPath), "utf8"));
    if ("error" in parsed) {
      blobListOk = setupProblem(`${blobListPath}: ${parsed.error}.`);
    } else {
      deniedBlobs = parsed.ids;
      const minimum = overrides.minBlobIds ?? LICENSED_PACK_BLOB_LIST_MIN_IDS;
      if (deniedBlobs.size < minimum) {
        blobListOk = setupProblem(
          `${blobListPath} holds ${deniedBlobs.size} id(s), fewer than the ${minimum} committed (LICENSED_PACK_BLOB_LIST_MIN_IDS); it looks emptied or truncated.`,
        );
      }
    }
  } catch (error) {
    blobListOk = setupProblem(`cannot read ${blobListPath}: ${error instanceof Error ? error.message : String(error)}.`);
  }

  let listing: { files: TrackedFile[]; gitlinks: string[] };
  try {
    listing = await listTrackedFiles(context.repoRoot);
  } catch (error) {
    return setupProblem(`cannot list tracked files: ${error instanceof Error ? error.message : String(error)}.`) && blobListOk;
  }
  for (const gitlink of listing.gitlinks) {
    console.error(`Licensed pack content check: not scanned, gitlink (submodule) ${gitlink}`);
  }

  const unreadable: string[] = [];
  const violations = await findLicensedPackContentViolations({
    files: listing.files,
    deniedBlobs,
    readText: async (repositoryPath) => {
      try {
        return decodeRepositoryText(repositoryPath, await readFile(path.join(context.repoRoot, repositoryPath)));
      } catch (error) {
        unreadable.push(`${repositoryPath} (${error instanceof Error ? error.message : String(error)})`);
        return undefined;
      }
    },
  });
  let readsOk = true;
  if (unreadable.length > 0) {
    readsOk = setupProblem(`${unreadable.length} tracked file(s) could not be read:\n${unreadable.map((entry) => `- ${entry}`).join("\n")}`);
  }
  return reportLicensedPackViolations(violations, mode) && blobListOk && readsOk;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const repoRoot = path.resolve(import.meta.dirname, "..");
  if (!(await checkLicensedPackContent({ repoRoot }))) process.exitCode = 1;
}
