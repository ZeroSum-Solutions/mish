function hasLicensedGenuiRow(value: unknown): boolean {
  if (Array.isArray(value)) return value.some(hasLicensedGenuiRow);
  if (value === null || typeof value !== "object") return false;
  const record = value as Record<string, unknown>;
  const source = record.source;
  if (
    record.licenceDecision === "licensed" &&
    source !== null &&
    typeof source === "object" &&
    (source as Record<string, unknown>).name === "cult-ui-pro"
  ) {
    return true;
  }
  return Object.values(record).some(hasLicensedGenuiRow);
}

/** A plugin manifest that names the MotionSites homepage, or a MotionSites author under CC-BY-4.0. */
export function isMotionSitesManifestText(text: string): boolean {
  if (MOTIONSITES_HOMEPAGE.test(text)) return true;
  const lower = text.toLowerCase();
  if (!lower.includes(MOTIONSITES_LICENCE)) return false;
  let manifest: unknown;
  try {
    manifest = JSON.parse(text);
  } catch {
    return false;
  }
  if (manifest === null || typeof manifest !== "object") return false;
  const record = manifest as Record<string, unknown>;
  const author = record.author;
  const authorName =
    typeof author === "string"
      ? author
      : author !== null && typeof author === "object"
        ? (author as Record<string, unknown>).name
        : undefined;
  const licence = record.license ?? record.licence;
  return (
    typeof authorName === "string" &&
    MOTIONSITES_AUTHOR_NAMES.some((name) => name.toLowerCase() === authorName.trim().toLowerCase()) &&
    typeof licence === "string" &&
    licence.trim().toLowerCase() === MOTIONSITES_LICENCE
  );
}

function isBinaryExtension(repositoryPath: string): boolean {
  return BINARY_EXTENSIONS.has(path.posix.extname(repositoryPath).toLowerCase());
}

const JSON_SUFFIX = /\.json(?:\.gz)?$/i;
const JSON_LEADING = /^\uFEFF?\s*[{[]/;

/** JSON by suffix, or by content: text that opens with `{` or `[`, whatever the file is called. */
function isJsonLike(repositoryPath: string, text: string): boolean {
  return JSON_SUFFIX.test(repositoryPath) || JSON_LEADING.test(text);
}

function shapeReasons(repositoryPath: string, text: string, switches: LicensedPackRuleSwitches): string[] {
  const reasons: string[] = [];
  const isJson = isJsonLike(repositoryPath, text);

  // Run on every text file, so a renamed or slightly edited copy still matches.
  if (CULT_REGISTRY_AUTHOR.test(text)) reasons.push("shape:cult-registry-author");
  if ((ADAPTER_SOURCE_SHA.test(text) && ADAPTER_CULT_ID.test(text)) || text.includes(ADAPTER_DERIVED_HEADER)) {
    reasons.push("shape:cult-adapter-signature");
  }
  if (CONVERTED_CSS_ROOT.test(text) || (CONVERTED_HTML_ROOT.test(text) && CONVERTED_HTML_UTILITIES.test(text))) {
    reasons.push("shape:cult-converted-markup");
  }
  if (isJson && isMotionSitesManifestText(text)) reasons.push("shape:motionsites-manifest");
  if (isJson && text.includes("cult-ui-pro") && text.includes("licensed")) {
    try {
      if (hasLicensedGenuiRow(JSON.parse(text.replace(/^\uFEFF/, "")))) reasons.push("shape:genui-cult-licensed-row");
    } catch {
      // Not parseable JSON: no catalog rows to inspect.
    }
  }
  if (isJson && GENUI_CULT_SEED_ROW.test(text)) reasons.push("shape:genui-cult-seed-row");
  if (isJson && switches.sectionCatalogCultProRule && SECTION_CATALOG_CULT_PRO.test(text)) {
    reasons.push("shape:section-catalog-cult-pro");
  }
  if ((path.posix.basename(repositoryPath).toLowerCase() === "pack.json" || isJson) && PACK_MANIFEST_FORMAT.test(text)) {
    reasons.push("shape:pack-manifest");
  }
  return reasons;
}

// ── Content: archive signatures and text decoding ────────────────────────

/** What the content rules need from a file: its text (when it has any) and the archive format its first bytes name. */
export type RepositoryContent = { text?: string; archive?: string };

/** Bytes read from a binary-extension file: enough for every signature below (tar needs 262). */
export const SNIFF_HEAD_BYTES = 512;

/** Upper bound on the bytes read from one file for the shape rules. */
export const MAX_SCAN_BYTES = 32 * 1024 * 1024;

const GZIP_OUTPUT_LIMIT = 64 * 1024 * 1024;

function startsWithBytes(bytes: Uint8Array, signature: readonly number[], offset = 0): boolean {
  return signature.every((byte, index) => bytes[offset + index] === byte);
}

/** Names the archive or compression format the bytes start with, or undefined. */
export function sniffArchiveKind(bytes: Uint8Array): string | undefined {
  if (startsWithBytes(bytes, [0x50, 0x4b, 0x03, 0x04]) || startsWithBytes(bytes, [0x50, 0x4b, 0x05, 0x06]) || startsWithBytes(bytes, [0x50, 0x4b, 0x07, 0x08])) return "zip";
  if (startsWithBytes(bytes, [0x1f, 0x8b])) return "gzip";
  // "BZh", a block-size digit, then the block magic 0x314159265359.
  if (startsWithBytes(bytes, [0x42, 0x5a, 0x68]) && startsWithBytes(bytes, [0x31, 0x41, 0x59, 0x26, 0x53, 0x59], 4)) return "bzip2";
  if (startsWithBytes(bytes, [0xfd, 0x37, 0x7a, 0x58, 0x5a, 0x00])) return "xz";
  if (startsWithBytes(bytes, [0x28, 0xb5, 0x2f, 0xfd])) return "zstd";
  if (startsWithBytes(bytes, [0x37, 0x7a, 0xbc, 0xaf, 0x27, 0x1c])) return "7z";
  if (startsWithBytes(bytes, [0x52, 0x61, 0x72, 0x21, 0x1a, 0x07])) return "rar";
  if (startsWithBytes(bytes, [0x75, 0x73, 0x74, 0x61, 0x72], 257)) return "tar";
  return undefined;
}

function decodeUtf16(bytes: Uint8Array, bigEndian: boolean): string {
  const even = Buffer.from(bytes.subarray(0, bytes.byteLength - (bytes.byteLength % 2)));
  return (bigEndian ? even.swap16() : even).toString("utf16le");
}

/**
 * Text of a byte buffer, or undefined for binary. A UTF-8 or UTF-16 byte order
 * mark is honoured and removed; UTF-16 without a mark is recognised by NUL
 * bytes at every other position. Any other NUL in the first 8000 bytes means
 * binary.
 */
export function decodeTextBytes(bytes: Buffer): string | undefined {
  if (startsWithBytes(bytes, [0xef, 0xbb, 0xbf])) return bytes.subarray(3).toString("utf8");
  if (startsWithBytes(bytes, [0xff, 0xfe])) return decodeUtf16(bytes.subarray(2), false);
  if (startsWithBytes(bytes, [0xfe, 0xff])) return decodeUtf16(bytes.subarray(2), true);
  const head = bytes.subarray(0, 8000);
  if (!head.includes(0)) return bytes.toString("utf8");
  let evenZeros = 0;
  let oddZeros = 0;
  for (let index = 0; index < head.length; index++) {
    if (head[index] !== 0) continue;
    if (index % 2 === 0) evenZeros++;
    else oddZeros++;
  }
  const pairs = Math.floor(head.length / 2);
  if (pairs >= 2 && oddZeros >= pairs * 0.3 && evenZeros <= pairs * 0.05) return decodeUtf16(bytes, false);
  if (pairs >= 2 && evenZeros >= pairs * 0.3 && oddZeros <= pairs * 0.05) return decodeUtf16(bytes, true);
  return undefined;
}

/**
 * Content for the rules from a file's bytes. Archive signatures win over the
 * suffix: a pack renamed to `.bin` is still an archive. Gzip is unpacked (an
 * undecodable gzip, or one that holds another archive, is reported as an
 * archive; one that holds text goes on to the shape rules). Binary extensions
 * are never decoded as text.
 */
export function decodeRepositoryContent(repositoryPath: string, bytes: Buffer): RepositoryContent {
  let archive = sniffArchiveKind(bytes);
  let content = bytes;
  if (archive === "gzip" && !isBinaryExtension(repositoryPath)) {
    try {
      content = gunzipSync(bytes, { maxOutputLength: GZIP_OUTPUT_LIMIT });
      const inner = sniffArchiveKind(content);
      archive = inner === undefined ? undefined : `gzip+${inner}`;
    } catch {
      // Not decodable (or too large to scan): report it as a gzip archive.
    }
  }
  if (archive !== undefined) return { archive };
  if (isBinaryExtension(repositoryPath)) return {};
  const text = decodeTextBytes(content);
  return text === undefined ? {} : { text };
}

