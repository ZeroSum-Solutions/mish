const MISH_MANIFEST = "mish.json";

/**
 * Every plugins/** folder whose manifest is a MotionSites manifest is
 * licensed as a whole, so a 19th example is caught without a name list.
 * Folders are returned lower-cased with a trailing slash.
 */
async function discoverMotionSitesFolders(
  manifests: readonly string[],
  readManifestText: (repositoryPath: string) => Promise<string | undefined>,
): Promise<string[]> {
  const folders = new Set<string>();
  for (const repositoryPath of manifests) {
    const text = await readManifestText(repositoryPath);
    if (text !== undefined && isMotionSitesManifestText(text)) {
      folders.add(`${path.posix.dirname(repositoryPath).toLowerCase()}/`);
    }
  }
  return [...folders];
}

function isPluginManifestPath(repositoryPath: string): boolean {
  return (
    repositoryPath.toLowerCase().startsWith("plugins/") &&
    path.posix.basename(repositoryPath).toLowerCase() === MISH_MANIFEST &&
    !isLicensedPackFixturePath(repositoryPath)
  );
}

function pathReasonsFor(repositoryPath: string, motionSitesFolders: readonly string[]): string[] {
  if (isLicensedPackFixturePath(repositoryPath)) return [];
  const lower = repositoryPath.toLowerCase();
  const reasons = LICENSED_PACK_PATH_RULES.filter((rule) => matchesPathRule(rule, repositoryPath)).map(
    (rule) => `path:${rule.id}`,
  );
  if (motionSitesFolders.some((folder) => lower.startsWith(folder))) {
    reasons.push(`path:${MOTIONSITES_FOLDER_RULE_ID}`);
  }
  return reasons;
}

/**
 * Path-rule matches only (rule family 1), keyed by repository path. Shared by
 * the guard and the blob-list generator so both see the same licensed set.
 */
export async function findLicensedPackPathMatches(
  paths: readonly string[],
  readText: ReadRepositoryText,
): Promise<Map<string, string[]>> {
  const motionSitesFolders = await discoverMotionSitesFolders(paths.filter(isPluginManifestPath), readText);
  const matches = new Map<string, string[]>();
  for (const repositoryPath of paths) {
    const reasons = pathReasonsFor(repositoryPath, motionSitesFolders);
    if (reasons.length > 0) matches.set(repositoryPath, reasons);
  }
  return matches;
}

/**
 * Applies every rule to every view in `files`. A path can appear more than
 * once (its index and working-tree views, or the stages of a conflicted
 * merge); the reasons of all its views are merged into one violation. A reason
 * found only in the working-tree view carries an `@worktree` suffix.
 */
export async function findLicensedPackContentViolations(input: {
  files: readonly TrackedFile[];
  readContent: ReadRepositoryContent;
  deniedBlobs: ReadonlySet<string>;
  rules?: LicensedPackRuleSwitches;
  reviewedStubs?: readonly ReviewedStub[];
}): Promise<LicensedPackViolation[]> {
  const switches = input.rules ?? LICENSED_PACK_RULE_SWITCHES;
  const reviewedStubs = input.reviewedStubs ?? LICENSED_PACK_REVIEWED_STUBS;

  const manifestViews = input.files.filter(
    (file) => (file.kind ?? "file") === "file" && isPluginManifestPath(file.path),
  );
  const folders = new Set<string>();
  for (const view of manifestViews) {
    const content = await input.readContent(view);
    if (content?.text !== undefined && isMotionSitesManifestText(content.text)) {
      folders.add(`${path.posix.dirname(view.path).toLowerCase()}/`);
    }
  }
  const motionSitesFolders = [...folders];

  const reasonsByPath = new Map<string, string[]>();
  const add = (repositoryPath: string, reasons: readonly string[]) => {
    if (reasons.length === 0) return;
    const merged = reasonsByPath.get(repositoryPath) ?? [];
    for (const reason of reasons) if (!merged.includes(reason)) merged.push(reason);
    reasonsByPath.set(repositoryPath, merged);
  };

  for (const file of input.files) {
    if (isReviewedLicensedPackStub(file, reviewedStubs)) continue;
    const kind = file.kind ?? "file";
    const suffix = file.tree === "worktree" ? "@worktree" : "";
    const pathReasons = pathReasonsFor(file.path, motionSitesFolders);
    const reasons = [...pathReasons];
    if (kind === "gitlink") {
      // A submodule holds no blob here and its content is not in this tree; the path rules still apply.
      add(file.path, reasons);
      continue;
    }
    if (isForbiddenTrackedArchive(file.path)) reasons.push(`path:${TRACKED_ARCHIVE_RULE_ID}`);
    const contentReasons: string[] = [];
    if (input.deniedBlobs.has(file.oid)) contentReasons.push("blob");

    // A path match already settles a file, so skip the content read there.
    // A symlink's content is its target text, never read through the link.
    if (kind === "file" && pathReasons.length === 0 && !isLicensedPackFixturePath(file.path)) {
      const content = await input.readContent(file);
      if (content?.archive !== undefined && !LICENSED_PACK_ARCHIVE_ALLOWLIST.includes(file.path)) {
        contentReasons.push(`archive:${content.archive}`);
      }
      if (content?.text !== undefined) contentReasons.push(...shapeReasons(file.path, content.text, switches));
    }
    add(file.path, [...reasons, ...contentReasons.map((reason) => `${reason}${suffix}`)]);
  }

  return [...reasonsByPath.entries()]
    .map(([repositoryPath, reasons]) => ({ path: repositoryPath, reasons }))
    .sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0));
}

// ── Blob ids and the denylist file ───────────────────────────────────────

/** The id `git hash-object` gives these bytes (SHA-1 object format). */
export function gitBlobId(bytes: Uint8Array): string {
  return createHash("sha1").update(`blob ${bytes.byteLength}\0`).update(bytes).digest("hex");
}

const BLOB_ID = /^[0-9a-f]{40}$/;

export function parseLicensedPackBlobList(text: string): { ids: Set<string> } | { error: string } {
  const ids = new Set<string>();
  const lines = text.split("\n");
  for (const [index, line] of lines.entries()) {
    if (line === "" && index === lines.length - 1) continue;
    if (!BLOB_ID.test(line)) return { error: `line ${index + 1} is not a git blob id` };
    ids.add(line);
  }
  return { ids };
}

export function formatLicensedPackBlobList(ids: Iterable<string>): string {
  const sorted = [...new Set(ids)].sort();
  return sorted.length === 0 ? "" : `${sorted.join("\n")}\n`;
}

// ── Mode and reporting ───────────────────────────────────────────────────

export function resolveLicensedPackGuardMode(
  value: string | undefined,
): { mode: LicensedPackGuardMode } | { error: string } {
  if (value === undefined || value === "") return { mode: DEFAULT_LICENSED_PACK_GUARD_MODE };
  if (value === "warn" || value === "enforce") return { mode: value };
  return { error: `${LICENSED_PACK_GUARD_MODE_ENV} must be "warn" or "enforce", got ${JSON.stringify(value)}` };
}

type GuardLog = { error: (line: string) => void; log: (line: string) => void };

// Label for warn-mode output from a stand-alone run; `pnpm guard` always
// runs in enforce mode and never prints it.
const ADVISORY_PREFIX = "advisory (on-demand check)";

/** Prints the violations and returns the check result for the mode. */
export function reportLicensedPackViolations(
  violations: readonly LicensedPackViolation[],
  mode: LicensedPackGuardMode,
  log: GuardLog = console,
): boolean {
  if (violations.length === 0) {
    log.log(`Licensed pack content check passed (${mode}): no licensed pack content in the tracked tree.`);
    return true;
  }
  if (mode === "warn") {
    log.error(
      `Licensed pack content (${ADVISORY_PREFIX}; ${LICENSED_PACK_GUARD_MODE_ENV}=enforce fails): ${violations.length} tracked file(s):`,
    );
    for (const violation of violations) {
      log.error(`- ${ADVISORY_PREFIX}: ${violation.path} [${violation.reasons.join(", ")}]`);
    }
    return true;
  }
  log.error(`Licensed pack content check failed: ${violations.length} tracked file(s) hold licensed pack content:`);
  for (const violation of violations) log.error(`- ${violation.path} [${violation.reasons.join(", ")}]`);
  return false;
}

