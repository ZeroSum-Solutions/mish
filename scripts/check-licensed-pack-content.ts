/**
 * Rejection is case-insensitive: macOS and Windows resolve `Catalog.json` to
 * `catalog.json`, so a case alias of a protected path is protected too. Only
 * the exemptions (fixture roots, reviewed stubs) stay exact.
 */
function matchesPathRule(rule: PathRule, repositoryPath: string): boolean {
  const lower = repositoryPath.toLowerCase();
  return (
    (rule.exact?.some((exact) => exact.toLowerCase() === lower) ?? false) ||
    (rule.prefixes?.some((prefix) => lower.startsWith(prefix.toLowerCase())) ?? false)
  );
}

