/* ─────────────────────────────────────────────────────────────────────────
 * scripts/check-licensed-pack-content.ts
 *
 * Licence guard (Licensed Pack plan, Phase 1 item 9). Keeps licensed pack
 * content — Cult UI Pro and MotionSites — out of the git-tracked tree that
 * becomes the public repository. Three rule families run on every tracked
 * file, and a file may match more than one:
 *
 *   1. Path rules (no content read): the Cult UI Pro kit, the Cult-keyed data
 *      in packages/cult-ui-catalog, the genui Cult seed and six port folders, and every plugin
 *      folder whose open-design.json names the MotionSites homepage.
 *   2. Blob rule: the git blob id of every tracked file (from
 *      `git ls-files -s`, no file read) against the committed denylist
 *      scripts/data/licensed-pack-blobs.txt, so a renamed or moved copy is
 *      caught at any path. Generated by scripts/generate-licensed-pack-blobs.ts.
 *   3. Shape rules (content read, every text file, gzip unpacked): Cult
 *      registry authors, derived adapter signatures, converted kit markup,
 *      MotionSites manifests, licensed genui catalog rows, and any
 *      `mishh-pack@1` pack.json.
 *   4. Archive rule (no content read): any tracked .tgz, .tar, .tar.gz or
 *      .zip. The shape rules cannot see inside an archive and a repacked
 *      archive has a new blob id, so a pack archive would pass rules 1-3;
 *      it is refused by extension instead.
 *
 * The known fixture roots (LICENSED_PACK_FIXTURE_ROOTS) are exempt from path,
 * shape and archive rules only; the blob rule applies everywhere, so a fixture can
 * never be a real licensed blob.
 *
 * Not registered in `pnpm guard` since 2026-10-08 (owner decision: Mishh-
 * Mashh-2 stays private, with no public release, so Phase 1 item 8 — strip
 * the licensed content and flip this check to enforce — is cancelled and
 * will not run). Run it on demand instead:
 * `pnpm exec tsx scripts/check-licensed-pack-content.ts`.
 *
 * Mode: LICENSED_PACK_GUARD_MODE unset (or `warn`) prints every violation
 * and passes without failing the run; `enforce` fails on any violation. Warn
 * is this check's permanent mode now that P1-8 is cancelled.
 *
 * Push-protection custom patterns are not available on the
 * ZeroSum-Solutions plan (Team, no Advanced Security).
 *
 * Run on demand: `pnpm exec tsx scripts/check-licensed-pack-content.ts`
 * ─────────────────────────────────────────────────────────────────────── */

