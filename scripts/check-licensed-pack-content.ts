type GitIndexEntry = TrackedFile & { stage: number };

/**
 * Index entries from `git ls-files -s -z`, one per stage (a conflicted merge
 * has up to three per path). The mode decides the kind: 160000 is a gitlink
 * (submodule), 120000 a symlink, anything else a regular file.
 */
async function listIndexEntries(repoRoot: string): Promise<GitIndexEntry[]> {
  const { stdout } = await execFileAsync("git", ["ls-files", "-s", "-z"], {
    cwd: repoRoot,
    encoding: "utf8",
    maxBuffer: 256 * 1024 * 1024,
  });
  const entries: GitIndexEntry[] = [];
  for (const record of stdout.split("\0")) {
    if (record === "") continue;
    const tab = record.indexOf("\t");
    const [mode, oid, stage] = record.slice(0, tab).split(" ");
    const repositoryPath = record.slice(tab + 1);
    if (mode === undefined || oid === undefined) continue;
    const kind = mode === "160000" ? "gitlink" : mode === "120000" ? "symlink" : "file";
    entries.push({ path: repositoryPath, oid, kind, tree: "index", stage: Number(stage ?? 0) });
  }
  return entries;
}

/** Tracked paths git considers modified or deleted in the working tree (clean filters applied). */
async function listWorkingTreeChanges(repoRoot: string): Promise<string[]> {
  const { stdout } = await execFileAsync("git", ["ls-files", "-m", "-d", "-z"], {
    cwd: repoRoot,
    encoding: "utf8",
    maxBuffer: 256 * 1024 * 1024,
  });
  return [...new Set(stdout.split("\0").filter((entry) => entry !== ""))];
}

/** Runs a git command and collects at most `limit` bytes of stdout; stops the child once the limit is passed. */
function gitStdoutBounded(
  repoRoot: string,
  args: readonly string[],
  limit: number,
  input?: string,
): Promise<{ bytes: Buffer; truncated: boolean }> {
  return new Promise((resolve, reject) => {
    const child = spawn("git", args, { cwd: repoRoot, stdio: ["pipe", "pipe", "pipe"] });
    const chunks: Buffer[] = [];
    let received = 0;
    let truncated = false;
    child.stdout.on("data", (chunk: Buffer) => {
      if (truncated) return;
      const room = limit - received;
      chunks.push(chunk.length > room ? chunk.subarray(0, room) : chunk);
      received += Math.min(chunk.length, room);
      if (chunk.length > room) {
        truncated = true;
        child.kill();
      }
    });
    child.stdin.on("error", () => {});
    child.on("error", reject);
    child.on("close", (code) => {
      if (code !== 0 && !truncated) reject(new Error(`git ${args[0]} exited with ${code}`));
      else resolve({ bytes: Buffer.concat(chunks), truncated });
    });
    child.stdin.end(input);
  });
}

/** The first `limit` bytes of a git blob. */
async function readBlobBounded(repoRoot: string, oid: string, limit: number): Promise<Buffer> {
  return (await gitStdoutBounded(repoRoot, ["cat-file", "blob", oid], limit)).bytes;
}

/**
 * The first `limit` bytes of a regular file, never through a symlink and never
 * from a device or pipe: the open refuses a link (O_NOFOLLOW), does not block
 * on a FIFO (O_NONBLOCK), and the opened descriptor must be a regular file.
 */
export async function readFileBounded(absolutePath: string, limit: number): Promise<Buffer> {
  const handle = await open(absolutePath, constants.O_RDONLY | (constants.O_NOFOLLOW ?? 0) | (constants.O_NONBLOCK ?? 0));
  try {
    if (!(await handle.stat()).isFile()) throw new Error("not a regular file");
    const size = Math.min((await handle.stat()).size, limit);
    const buffer = Buffer.alloc(size);
    let filled = 0;
    while (filled < size) {
      const { bytesRead } = await handle.read(buffer, filled, size - filled, filled);
      if (bytesRead === 0) break;
      filled += bytesRead;
    }
    return buffer.subarray(0, filled);
  } finally {
    await handle.close();
  }
}

type WorkingTreeState = {
  /** Working-tree blob id (git's clean filters applied) of each regular file that differs from the index. */
  changed: Map<string, string>;
  /** Tracked paths missing from the working tree. */
  deleted: string[];
  /** Tracked paths that are no longer regular files on disk (a symlink or directory took their place). */
  nonRegular: string[];
  /** Paths whose working-tree bytes could not be hashed. */
  unhashable: string[];
};

async function inspectWorkingTree(repoRoot: string, candidates: readonly string[]): Promise<WorkingTreeState> {
  const state: WorkingTreeState = { changed: new Map(), deleted: [], nonRegular: [], unhashable: [] };
  const regular: string[] = [];
  for (const repositoryPath of candidates) {
    try {
      const stats = await lstat(path.join(repoRoot, repositoryPath));
      if (stats.isFile()) regular.push(repositoryPath);
      else state.nonRegular.push(repositoryPath);
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code === "ENOENT") state.deleted.push(repositoryPath);
      else state.unhashable.push(repositoryPath);
    }
  }
  // `git hash-object <path>` applies the path's clean filters (core.autocrlf,
  // .gitattributes eol), so the id is the one `git add` would record.
  const batchable = regular.filter((repositoryPath) => !repositoryPath.includes("\n"));
  if (batchable.length > 0) {
    try {
      const { bytes } = await gitStdoutBounded(repoRoot, ["hash-object", "--stdin-paths"], 64 * 1024 * 1024, `${batchable.join("\n")}\n`);
      const oids = bytes.toString("utf8").split("\n").filter((line) => line !== "");
      if (oids.length === batchable.length) {
        batchable.forEach((repositoryPath, index) => state.changed.set(repositoryPath, oids[index]!));
      } else {
        state.unhashable.push(...batchable);
      }
    } catch {
      state.unhashable.push(...batchable);
    }
  }
  for (const repositoryPath of regular.filter((entry) => entry.includes("\n"))) {
    try {
      const { bytes } = await gitStdoutBounded(repoRoot, ["hash-object", "--", repositoryPath], 4096);
      state.changed.set(repositoryPath, bytes.toString("utf8").trim());
    } catch {
      state.unhashable.push(repositoryPath);
    }
  }
  return state;
}

export async function checkLicensedPackContent(
  context: { repoRoot: string },
  overrides: { mode?: string; blobListPath?: string; minBlobIds?: number } = {},
): Promise<boolean> {
  const resolved = resolveLicensedPackGuardMode(overrides.mode ?? process.env[LICENSED_PACK_GUARD_MODE_ENV]);
  if ("error" in resolved) {
    console.error(`Licensed pack content check failed: ${resolved.error}.`);
    return false;
  }
  const { mode } = resolved;
  // In warn mode a broken input is reported and passes; enforce fails closed.
  const setupProblem = (message: string): boolean => {
    console.error(
      mode === "warn"
        ? `Licensed pack content (${ADVISORY_PREFIX}): ${message}`
        : `Licensed pack content check failed: ${message}`,
    );
    return mode === "warn";
  };

  const blobListPath = overrides.blobListPath ?? LICENSED_PACK_BLOB_LIST_PATH;
  let deniedBlobs = new Set<string>();
  let blobListOk = true;
  try {
    const parsed = parseLicensedPackBlobList(await readFile(path.join(context.repoRoot, blobListPath), "utf8"));
    if ("error" in parsed) {
      blobListOk = setupProblem(`${blobListPath}: ${parsed.error}.`);
    } else {
      deniedBlobs = parsed.ids;
      const minimum = overrides.minBlobIds ?? LICENSED_PACK_BLOB_LIST_MIN_IDS;
      if (deniedBlobs.size < minimum) {
        blobListOk = setupProblem(
          `${blobListPath} holds ${deniedBlobs.size} id(s), fewer than the ${minimum} committed (LICENSED_PACK_BLOB_LIST_MIN_IDS); it looks emptied or truncated.`,
        );
      }
    }
  } catch (error) {
    blobListOk = setupProblem(`cannot read ${blobListPath}: ${error instanceof Error ? error.message : String(error)}.`);
  }

  let indexEntries: GitIndexEntry[];
  let working: WorkingTreeState;
  try {
    indexEntries = await listIndexEntries(context.repoRoot);
    const regularPaths = new Set(indexEntries.filter((entry) => entry.kind === "file").map((entry) => entry.path));
    working = await inspectWorkingTree(
      context.repoRoot,
      (await listWorkingTreeChanges(context.repoRoot)).filter((repositoryPath) => regularPaths.has(repositoryPath)),
    );
  } catch (error) {
    return setupProblem(`cannot list tracked files: ${error instanceof Error ? error.message : String(error)}.`) && blobListOk;
  }

  // Each regular file whose working bytes differ from its index blob gets a
  // second, working-tree view. When they hash alike (git only saw a stat
  // change, or a CRLF checkout), the disk holds the index bytes and one view is enough.
  const files: TrackedFile[] = indexEntries.map(({ stage: _stage, ...entry }) => entry);
  const blobSourced = new Set<string>([
    ...working.deleted,
    ...working.nonRegular,
    ...working.unhashable,
    ...indexEntries.filter((entry) => entry.stage !== 0).map((entry) => entry.path),
  ]);
  for (const [repositoryPath, workingOid] of working.changed) {
    const differs = indexEntries.some((entry) => entry.path === repositoryPath && entry.oid !== workingOid);
    if (!differs) continue;
    blobSourced.add(repositoryPath);
    files.push({ path: repositoryPath, oid: workingOid, kind: "file", tree: "worktree" });
  }

  for (const gitlink of files.filter((file) => file.kind === "gitlink")) {
    console.error(`Licensed pack content check: gitlink (submodule) ${gitlink.path}: only the path rules apply, its content is not in this tree`);
  }
  if (working.deleted.length > 0) {
    console.log(
      `Licensed pack content check: ${working.deleted.length} tracked file(s) are deleted in the working tree; their index blobs were scanned instead.`,
    );
  }

  const unreadable: string[] = [];
  const readContent: ReadRepositoryContent = async (file) => {
    if ((file.kind ?? "file") !== "file") return undefined;
    const limit = isBinaryExtension(file.path) ? SNIFF_HEAD_BYTES : MAX_SCAN_BYTES;
    try {
      const fromBlob = file.tree !== "worktree" && blobSourced.has(file.path);
      const bytes = fromBlob
        ? await readBlobBounded(context.repoRoot, file.oid, limit)
        : await readFileBounded(path.join(context.repoRoot, file.path), limit);
      return decodeRepositoryContent(file.path, bytes);
    } catch (error) {
      unreadable.push(`${file.path} (${error instanceof Error ? error.message : String(error)})`);
      return undefined;
    }
  };

  const violations = await findLicensedPackContentViolations({ files, deniedBlobs, readContent });
  let readsOk = true;
  const unread = [...new Set([...unreadable, ...working.unhashable.map((entry) => `${entry} (could not hash the working-tree file)`)])];
  if (unread.length > 0) {
    readsOk = setupProblem(`${unread.length} tracked file(s) could not be read:\n${unread.map((entry) => `- ${entry}`).join("\n")}`);
  }
  return reportLicensedPackViolations(violations, mode) && blobListOk && readsOk;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const repoRoot = path.resolve(import.meta.dirname, "..");
  if (!(await checkLicensedPackContent({ repoRoot }))) process.exitCode = 1;
}
