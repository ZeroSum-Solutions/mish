/* ─────────────────────────────────────────────────────────────────────────
 * scripts/check-licensed-pack-content.ts
 *
 * Licence guard (Licensed Pack plan, Phase 1 item 9). Keeps licensed pack
 * content — Cult UI Pro and MotionSites — out of the git-tracked tree that
 * becomes the public repository. Four rule families run on every tracked
 * entry, and an entry may match more than one:
 *
 *   1. Path rules (no content read): the Cult UI Pro kit, the Cult-keyed data
 *      in packages/cult-ui-catalog, the genui Cult seed and six port folders, and every plugin
 *      folder whose mish.json names the MotionSites homepage. Matching ignores
 *      letter case, so `Catalog.json` cannot slip past a `catalog.json` rule on
 *      a case-insensitive file system. Gitlinks (submodules) and symlinks get
 *      these rules too.
 *   2. Blob rule: the git blob id of every tracked file against the committed
 *      denylist scripts/data/licensed-pack-blobs.txt, so a renamed or moved
 *      copy is caught at any path. Generated by scripts/generate-licensed-pack-blobs.ts.
 *   3. Shape rules (content read, every text file, gzip unpacked): Cult
 *      registry authors, derived adapter signatures, converted kit markup,
 *      MotionSites manifests, licensed genui catalog rows, and any
 *      `mishh-pack@1` pack.json. JSON rules key on the content (a leading `{`
 *      or `[`) as well as the suffix, and UTF-16 and BOM-marked text is decoded
 *      first, so a rename or a re-encode does not hide a manifest.
 *   4. Archive rule: any tracked .tgz, .tar, .tar.gz, .zip (and the other
 *      common archive suffixes), and any file whose first bytes are an archive
 *      signature (zip, gzip, bzip2, xz, zstd, 7z, rar, tar), whatever it is
 *      called. The shape rules cannot see inside an archive and a repacked
 *      archive has a new blob id, so a pack archive would pass rules 1-3.
 *
 * Two views of the tree are scanned. The index view is what a commit would
 * hold: the git blob of every entry. The working-tree view adds a second entry
 * for each file whose working bytes differ from the index (after git's own
 * clean filters, so core.autocrlf does not make a clean checkout look
 * modified). Each rule sees both views, so a file staged with licensed content
 * and then overwritten, or the reverse, is still flagged. A tracked file
 * deleted from the working tree is scanned from the index and reported once.
 * Reads are bounded and never follow a symlink.
 *
 * The known fixture roots (LICENSED_PACK_FIXTURE_ROOTS) are exempt from path,
 * shape and archive rules only; the blob rule applies everywhere, so a fixture can
 * never be a real licensed blob. Fixture matching is exact (case-sensitive).
 *
 * Reviewed public stubs (LICENSED_PACK_REVIEWED_STUBS) are exempt from every
 * rule, but only as an exact (path, git blob id) pair, checked per view: the
 * same path with any other bytes, or the same bytes at any other path (or in
 * another letter case), is checked as usual.
 *
 * The repository is public. `pnpm guard` runs this check as "licensed pack
 * content" in enforce mode, so any violation fails the guard whatever
 * LICENSED_PACK_GUARD_MODE says. Licensed content belongs in a private pack
 * (docs/packs.md).
 *
 * Mode for the stand-alone run: LICENSED_PACK_GUARD_MODE unset (or `warn`)
 * prints every violation and passes; `enforce` fails on any violation.
 *
 * Push-protection custom patterns are not available on the
 * ZeroSum-Solutions plan (Team, no Advanced Security).
 *
 * Run alone: `LICENSED_PACK_GUARD_MODE=enforce node scripts/check-licensed-pack-content.ts`
 * ─────────────────────────────────────────────────────────────────────── */

