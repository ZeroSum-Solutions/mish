/**
 * One view of one tracked entry. `tree` says which tree the bytes are from:
 * "index" (the blob a commit would hold, the default) or "worktree" (the file
 * on disk, listed only when it differs from the index). `kind` is the git
 * mode class: a symlink or gitlink has no file content to scan.
 */
export type TrackedFile = {
  path: string;
  oid: string;
  kind?: "file" | "symlink" | "gitlink";
  tree?: "index" | "worktree";
};

export type LicensedPackViolation = { path: string; reasons: string[] };

/** Resolves to the file's content, or undefined when there is none to read. Throws when unreadable. */
