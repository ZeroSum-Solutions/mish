/**
 * Generate packages/linkpage/src/catalog-assets.ts: the CSS and auto-mount script of the few GenUI
 * catalog components a link page may use, as plain strings.
 *
 * Why a generated, committed file: @mish/linkpage is headless (no filesystem, no import of
 * packages/genui-catalog), so the text it inlines has to be inside its own source. Same idea as
 * packages/genui-catalog/scripts/sync-catalog-assets.ts, with one target instead of many.
 *
 * Every id must be a catalog.json entry with status "ported" and licenceDecision "clean-room", and the
 * lists must equal the ones in packages/contracts/src/api/linkpage.ts. A css-only component ships no script.
 *
 * Usage (run `pnpm --filter @mish/genui-catalog build` first; the text comes from dist/):
 *   node --experimental-strip-types scripts/sync-linkpage-catalog.ts
 *   node --experimental-strip-types scripts/sync-linkpage-catalog.ts --check   (writes nothing, exits 1 on drift)
 */

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { LINKPAGE_EFFECT_BACKGROUNDS, LINKPAGE_EFFECT_HOVERS } from '../packages/contracts/src/api/linkpage.ts';

const repoRoot = path.resolve(import.meta.dirname, '..');
const catalogDir = path.join(repoRoot, 'packages/genui-catalog');
const target = path.join(repoRoot, 'packages/linkpage/src/catalog-assets.ts');

export interface SyncReport { drift: string[]; errors: string[]; bytes: number }

interface Entry { id: string; kind?: string; status?: string; licenceDecision?: string }

function render(backgrounds: readonly string[], hovers: readonly string[], assets: Record<string, { css: string; js: string }>): string {
  const body = Object.entries(assets).map(([id, a]) => `  ${JSON.stringify(id)}: {\n    css: ${JSON.stringify(a.css)},\n    js: ${JSON.stringify(a.js)},\n  },`).join('\n');
  return `// GENERATED by scripts/sync-linkpage-catalog.ts from packages/genui-catalog/dist. Do not edit by hand.
// Clean-room GenUI catalog components a link page may use. \`js\` is empty for a css-only component.

export const BACKGROUND_IDS = ${JSON.stringify(backgrounds)} as const;
export const HOVER_IDS = ${JSON.stringify(hovers)} as const;

export const CATALOG_ASSETS: Record<string, { css: string; js: string }> = {
${body}
};
`;
}

export function syncLinkpageCatalog({ check = false }: { check?: boolean } = {}): SyncReport {
  const report: SyncReport = { drift: [], errors: [], bytes: 0 };
  const catalog = JSON.parse(readFileSync(path.join(catalogDir, 'catalog.json'), 'utf8')) as { components?: Entry[] } | Entry[];
  const entries = Array.isArray(catalog) ? catalog : catalog.components ?? [];
  const assets: Record<string, { css: string; js: string }> = {};
  for (const id of [...LINKPAGE_EFFECT_BACKGROUNDS, ...LINKPAGE_EFFECT_HOVERS]) {
    const entry = entries.find((e) => e.id === id);
    if (!entry) { report.errors.push(`${id}: not in catalog.json`); continue; }
    if (entry.status !== 'ported' || entry.licenceDecision !== 'clean-room') { report.errors.push(`${id}: needs status ported and licenceDecision clean-room`); continue; }
    const dir = path.join(catalogDir, 'dist/components', id);
    if (!existsSync(path.join(dir, 'styles.css'))) { report.errors.push(`${id}: dist is missing (run pnpm --filter @mish/genui-catalog build)`); continue; }
    const css = readFileSync(path.join(dir, 'styles.css'), 'utf8').trim();
    const js = entry.kind === 'css-only' ? '' : readFileSync(path.join(dir, 'auto.js'), 'utf8').trim();
    if (/<\/(style|script)|<!--/i.test(css + js)) { report.errors.push(`${id}: contains a closing tag or comment opener and cannot be inlined`); continue; }
    assets[id] = { css, js };
    report.bytes += Buffer.byteLength(css) + Buffer.byteLength(js);
  }
  if (report.errors.length) return report;
  const next = render(LINKPAGE_EFFECT_BACKGROUNDS, LINKPAGE_EFFECT_HOVERS, assets);
  const current = existsSync(target) ? readFileSync(target, 'utf8') : '';
  if (current !== next) {
    if (check) report.drift.push(path.relative(repoRoot, target));
    else writeFileSync(target, next);
  }
  return report;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const check = process.argv.includes('--check');
  const report = syncLinkpageCatalog({ check });
  for (const e of report.errors) console.error(`error: ${e}`);
  for (const d of report.drift) console.error(`drift: ${d} (run: node --experimental-strip-types scripts/sync-linkpage-catalog.ts)`);
  if (report.errors.length || report.drift.length) process.exit(1);
  console.log(`${check ? 'in sync' : 'synced'}: ${report.bytes} bytes of catalog assets`);
}
