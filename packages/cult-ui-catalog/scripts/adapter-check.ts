/**
 * The Cult adapter gate. Checks the committed `generated/` tree against catalog.json and, when the
 * private source kit is present, against the kit's converter output and pinned registry snapshot.
 *
 * Always (CI included):
 *   - the insertable catalog rows, `generated/index.ts`'s registry and `generated/adapters/*.ts`
 *     name exactly the same blocks, and the index and the shim equal what the writer would emit;
 *   - each adapter's id, sourceBlockId, version and sourceSha256 equal its catalog row;
 *   - the product's own adapter rules (`scripts/build-section-adapters.ts` FORBIDDEN/assertClean)
 *     pass on the CSS and on the worst-case render; the CSS reads only `var(--role-*)` or custom
 *     properties it sets itself (an unset converter `--k-*` variable fails too: its declaration
 *     would never paint), and every style rule is scoped under `.cult-<name>`;
 *   - a worst-case fill (every slot at its maximum length) validates and renders through the
 *     shared `renderSectionAdapter`, and its minified HTML plus the CSS stay within
 *     ADAPTER_BYTE_LIMIT;
 *   - a row's preview, when it names one, exists and is within PREVIEW_BYTE_LIMIT.
 * With the kit:
 *   - each generated file equals `productAdapterSource(converted/<name>/adapter.ts)`;
 *   - each adapter's sourceSha256 equals the hash recomputed from `registry/<name>.json` (for a
 *     section cut from a page, the page's item) with src/converted.ts `converterSourceSha`, the
 *     converter's own formula.
 */

import { existsSync, readdirSync, readFileSync, statSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

import {
  ADAPTER_BYTE_LIMIT,
  converterSourceSha,
  cultAdapterId,
  PREVIEW_BYTE_LIMIT,
  productAdapterSource,
} from '../src/converted.ts';
import type { CultCatalog, CultCatalogRow } from '../src/types.ts';

type TextSlot = { name: string; max: number; atom?: 'phone' | 'email' | 'address' | 'plain' };
type Adapter = {
  id: string;
  version: string;
  sourceBlockId: string;
  sourceSha256: string;
  roles: readonly string[];
  text: readonly TextSlot[];
  items?: { name: string; count: number; fields: readonly TextSlot[] };
  links?: readonly { name: string; href: string; label?: string }[];
  assets?: readonly unknown[];
  css: string;
  render: (fill: unknown) => string;
};
type Fill = { text: Record<string, string>; items?: Record<string, Array<Record<string, string>>> };
type ProductRules = {
  assertClean: (label: string, source: string) => void;
  validateAdapterFill: (adapter: Adapter, fill: Fill) => Array<{ slot: string; reason: string }>;
  renderSectionAdapter: (adapter: Adapter, fill: Fill) => string;
  SEMANTIC_ROLES: readonly string[];
};

export const PACKAGE_DIR = resolve(import.meta.dirname, '..');
const REPO_ROOT = resolve(PACKAGE_DIR, '..', '..');
const SHARED_ADAPTER_MODULE = 'plugins/_official/shared/agency-compiler/scripts/section-adapter.ts';

/** Loaded by path (not a static import) so this package's `tsc` never compiles the root script. */
async function loadProductRules(): Promise<ProductRules> {
  const build = await import(pathToFileURL(join(REPO_ROOT, 'scripts', 'build-section-adapters.ts')).href) as Pick<ProductRules, 'assertClean'>;
  const shared = await import(pathToFileURL(join(REPO_ROOT, SHARED_ADAPTER_MODULE)).href) as Omit<ProductRules, 'assertClean'>;
  return { assertClean: build.assertClean, ...shared };
}

