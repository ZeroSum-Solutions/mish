export function shimSource(): string {
  return `// GENERATED by packages/cult-ui-catalog/scripts/adapters.ts — do not edit by hand.
// The generated Cult adapters import the shared SectionAdapter contract through this one file, so
// the path into the shared agency compiler is written once. The adapters live here, not in the
// shared compiler, so scripts/sync-agency-compiler.ts never copies them into family packages.

export { escapeHtml, renderSectionAdapter, validateAdapterFill, SEMANTIC_ROLES } from '../../../${SHARED_ADAPTER_MODULE}';
export type { AdapterFill, SectionAdapter, SemanticRole } from '../../../${SHARED_ADAPTER_MODULE}';
`;
}

export function indexSource(names: readonly string[]): string {
  const sorted = [...names].sort();
  const lines = sorted.map((name) => `  '${cultAdapterId(name)}': () => import('./adapters/${name}.ts').then((m) => m.ADAPTER),`);
  return `// GENERATED by packages/cult-ui-catalog/scripts/adapters.ts — do not edit by hand.
// The checked Cult adapter registry: one lazy loader per insertable catalog row, keyed by the
// catalog id (\`cult:<name>\`). A caller imports only the adapters it selects.

import type { SectionAdapter } from './section-adapter.ts';

export type CultAdapterLoader = () => Promise<SectionAdapter>;

export const CULT_ADAPTERS: Readonly<Record<string, CultAdapterLoader>> = Object.freeze({
${lines.join('\n')}
});

export const CULT_ADAPTER_IDS: readonly string[] = Object.freeze(Object.keys(CULT_ADAPTERS));
`;
}

