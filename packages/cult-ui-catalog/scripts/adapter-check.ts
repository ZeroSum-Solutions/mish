/** A value of exactly `max` characters that satisfies the slot's atom kind. */
function worstValue(slot: TextSlot): string {
  if (slot.atom === 'email') return `${'w'.repeat(Math.max(1, slot.max - 12))}@example.com`.slice(-slot.max);
  if (slot.atom === 'phone') return '+1 (555) 010-0199'.slice(0, Math.min(slot.max, 17));
  return 'W'.repeat(slot.max);
}

export function worstCaseFill(adapter: Adapter): Fill {
  const text: Record<string, string> = {};
  for (const slot of adapter.text) text[slot.name] = worstValue(slot);
  if (!adapter.items) return { text };
  const row: Record<string, string> = {};
  for (const field of adapter.items.fields) row[field.name] = worstValue(field);
  return { text, items: { [adapter.items.name]: Array.from({ length: adapter.items.count }, () => ({ ...row })) } };
}

export function minifiedHtml(html: string): string {
  return html.replace(/>\s+</g, '><');
}

/**
 * Custom properties the CSS reads from outside itself: read with no fallback, never defined or
 * registered (`@property`) in the same CSS, and not part of the `--role-*` contract. A read with a
 * fallback (`var(--k-ease,cubic-bezier(…))`, Tailwind's own idiom) is self-sufficient.
 */
export function foreignCustomProperties(css: string): string[] {
  const defined = new Set([
    ...[...css.matchAll(/(--[\w-]+)\s*:/g)].map((m) => m[1]!),
    ...[...css.matchAll(/@property\s+(--[\w-]+)/g)].map((m) => m[1]!),
  ]);
  const bare = new Set([...css.matchAll(/var\(\s*(--[\w-]+)\s*\)/g)].map((m) => m[1]!));
  return [...bare].filter((name) => !name.startsWith('--role-') && !defined.has(name)).sort();
}

/** Splits a selector list on top-level commas (not the ones inside `:where(…)`/`:is(…)`). */
function splitSelectors(prelude: string): string[] {
  const out: string[] = [];
  let depth = 0;
  let start = 0;
  for (let i = 0; i < prelude.length; i += 1) {
    const c = prelude[i];
    if (c === '(') depth += 1;
    else if (c === ')') depth -= 1;
    else if (c === ',' && depth === 0) {
      out.push(prelude.slice(start, i));
      start = i + 1;
    }
  }
  out.push(prelude.slice(start));
  return out.map((s) => s.trim()).filter((s) => s.length > 0);
}

const KEYFRAME_SELECTOR = /^(from|to|\d+(\.\d+)?%)(\s*,\s*(from|to|\d+(\.\d+)?%))*$/;

/** Style-rule selectors not scoped under `scope` (a class selector such as `.cult-x`). */
export function unscopedSelectors(css: string, scope: string): string[] {
  const out: string[] = [];
  const withoutComments = css.replace(/\/\*[\s\S]*?\*\//g, '');
  for (const match of withoutComments.matchAll(/([^{}]+)\{/g)) {
    const prelude = match[1]!.trim();
    if (prelude.startsWith('@') || KEYFRAME_SELECTOR.test(prelude)) continue;
    for (const s of splitSelectors(prelude)) {
      if (!new RegExp(`${scope.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}(?![\\w-])`).test(s)) out.push(s);
    }
  }
  return out;
}

export interface AdapterMeasure {
  id: string;
  htmlMin: number;
  cssMin: number;
  total: number;
}

export interface AdapterCheckResult {
  errors: string[];
  notes: string[];
  measured: AdapterMeasure[];
  kitCompared: boolean;
}

export interface AdapterCheckOptions {
  catalog: CultCatalog;
  /** Directory holding `index.ts`, `section-adapter.ts`, `adapters/` and `previews/`. */
  generatedDir: string;
  /** The private source kit; null or missing skips the kit comparison. */
  kitDir: string | null;
}

function listAdapterFiles(dir: string): string[] {
  if (!existsSync(dir)) return [];
  return readdirSync(dir).filter((f) => f.endsWith('.ts')).map((f) => f.slice(0, -'.ts'.length)).sort();
}

function sameSet(a: readonly string[], b: readonly string[]): boolean {
  return a.length === b.length && [...a].sort().every((v, i) => v === [...b].sort()[i]);
}

async function checkOne(row: CultCatalogRow, generatedDir: string, rules: ProductRules, kitDir: string | null, result: AdapterCheckResult): Promise<void> {
  const at = row.id;
  const err = (message: string) => result.errors.push(`${at}: ${message}`);
  const file = join(generatedDir, 'adapters', `${row.name}.ts`);
  let adapter: Adapter;
  try {
    adapter = (await import(pathToFileURL(file).href) as { ADAPTER: Adapter }).ADAPTER;
  } catch (error) {
    err(`adapter module does not load: ${(error as Error).message}`);
    return;
  }
  const ref = row.adapter;
  if (adapter.id !== row.id) err(`adapter id ${adapter.id} is not the row id`);
  if (adapter.sourceBlockId !== row.id) err(`sourceBlockId ${adapter.sourceBlockId} is not the row id`);
  if (!ref || adapter.version !== ref.version) err(`version ${adapter.version} differs from catalog.json (${ref?.version ?? 'none'})`);
  if (!ref || adapter.sourceSha256 !== ref.sourceSha256) err('sourceSha256 differs from catalog.json');
  if ((adapter.assets ?? []).length > 0) err('Cult adapters carry no assets in v1');
  for (const role of adapter.roles) if (!rules.SEMANTIC_ROLES.includes(role)) err(`unknown role ${role}`);
  for (const link of adapter.links ?? []) if (!/^#[a-z0-9-]+$/.test(link.href)) err(`link ${link.name} is not a fixed in-page anchor`);

  const scope = `.cult-${row.name}`;
  // Every custom property the CSS reads must be a `--role-*` or be set by the CSS itself. An unset
  // name the host page could set is a leak; an unset `--k-*` (the converter's renamed Tailwind
  // namespace) makes its declaration invalid, so a gradient or filter silently never paints. Both fail.
  const foreign = foreignCustomProperties(adapter.css);
  const leaked = foreign.filter((name) => !name.startsWith('--k-'));
  const unset = foreign.filter((name) => name.startsWith('--k-'));
  if (leaked.length > 0) err(`CSS reads custom properties outside the --role-* contract: ${leaked.join(', ')}`);
  if (unset.length > 0) err(`CSS reads converter variables it never sets: ${unset.join(', ')}; fix the kit converter and re-run it`);
  const unscoped = unscopedSelectors(adapter.css, scope);
  if (unscoped.length > 0) err(`CSS rules not scoped under ${scope}: ${unscoped.slice(0, 3).join(' | ')}`);
  try {
    rules.assertClean(`${at} css`, adapter.css);
  } catch (error) {
    err((error as Error).message);
  }

  const fill = worstCaseFill(adapter);
  const fillErrors = rules.validateAdapterFill(adapter, fill);
  if (fillErrors.length > 0) {
    err(`worst-case fill rejected: ${fillErrors.slice(0, 3).map((e) => `${e.slot}: ${e.reason}`).join('; ')}`);
    return;
  }
  const html = minifiedHtml(rules.renderSectionAdapter(adapter, fill));
  if (!html.startsWith(`<div class="${scope.slice(1)}"`)) err(`render does not start with its ${scope} scope element`);
  try {
    rules.assertClean(`${at} worst-case render`, html);
  } catch (error) {
    err((error as Error).message);
  }
  const measure = { id: at, htmlMin: Buffer.byteLength(html, 'utf8'), cssMin: Buffer.byteLength(adapter.css, 'utf8'), total: 0 };
  measure.total = measure.htmlMin + measure.cssMin;
  result.measured.push(measure);
  if (measure.total > ADAPTER_BYTE_LIMIT) err(`worst-case HTML+CSS is ${measure.total} B, over the ${ADAPTER_BYTE_LIMIT} B limit`);

  if (row.previewId !== null) {
    const preview = join(generatedDir, 'previews', row.previewId);
    if (!existsSync(preview)) err(`preview ${row.previewId} is missing`);
    else if (statSync(preview).size > PREVIEW_BYTE_LIMIT) err(`preview ${row.previewId} is over ${PREVIEW_BYTE_LIMIT} B`);
  }

  if (kitDir === null) return;
  const kitAdapter = join(kitDir, 'converted', row.name, 'adapter.ts');
  if (!existsSync(kitAdapter)) {
    err('the kit has no converted adapter for this row');
  } else {
    try {
      if (readFileSync(file, 'utf8') !== productAdapterSource(readFileSync(kitAdapter, 'utf8'), row.name)) {
        err('generated adapter differs from the kit\'s converted output; run `pnpm --filter @open-design/cult-ui-catalog adapters`');
      }
    } catch (error) {
      err(`kit adapter cannot be copied: ${(error as Error).message}`);
    }
  }
  // A derived section's adapter hashes its whole page item (the converter's `sourceSha`).
  const registryName = row.derivedFrom !== undefined ? row.derivedFrom.slice('cult:'.length) : row.name;
  const registryItem = join(kitDir, 'registry', `${registryName}.json`);
  if (!existsSync(registryItem)) {
    err('the kit has no registry item for this row');
  } else {
    const item = JSON.parse(readFileSync(registryItem, 'utf8')) as { files?: Array<{ path: string; content?: string }> };
    const sha = converterSourceSha((item.files ?? []).map((f) => ({ path: f.path, content: f.content ?? '' })));
    if (sha !== adapter.sourceSha256) err(`sourceSha256 does not match the pinned registry item (recomputed ${sha})`);
  }
}

export async function checkAdapters(options: AdapterCheckOptions): Promise<AdapterCheckResult> {
  const { catalog, generatedDir } = options;
  const kitDir = options.kitDir !== null && existsSync(join(options.kitDir, 'converted')) ? options.kitDir : null;
  const result: AdapterCheckResult = { errors: [], notes: [], measured: [], kitCompared: kitDir !== null };
  const rows = catalog.rows.filter((row) => row.conversion.status === 'insertable');
  const names = rows.map((row) => row.name);

  const files = listAdapterFiles(join(generatedDir, 'adapters'));
  if (!sameSet(files, names)) {
    const extra = files.filter((f) => !names.includes(f));
    const missing = names.filter((n) => !files.includes(n));
    result.errors.push(`generated/adapters differs from the insertable rows (extra: ${extra.join(', ') || 'none'}; missing: ${missing.join(', ') || 'none'})`);
  }
  const indexPath = join(generatedDir, 'index.ts');
  if (!existsSync(indexPath) || readFileSync(indexPath, 'utf8') !== indexSource(names)) {
    result.errors.push('generated/index.ts is out of date with catalog.json');
  }
  const shimPath = join(generatedDir, 'section-adapter.ts');
  if (!existsSync(shimPath) || readFileSync(shimPath, 'utf8') !== shimSource()) result.errors.push('generated/section-adapter.ts is out of date');
  try {
    const registry = await import(pathToFileURL(indexPath).href) as { CULT_ADAPTER_IDS?: readonly string[] };
    if (!sameSet(registry.CULT_ADAPTER_IDS ?? [], rows.map((row) => row.id))) result.errors.push('generated/index.ts registry ids differ from the insertable rows');
  } catch (error) {
    result.errors.push(`generated/index.ts does not load: ${(error as Error).message}`);
  }

  const rules = await loadProductRules();
  for (const row of rows) {
    if (!files.includes(row.name)) continue;
    await checkOne(row, generatedDir, rules, kitDir, result);
  }
  const previews = existsSync(join(generatedDir, 'previews')) ? readdirSync(join(generatedDir, 'previews')) : [];
  const wanted = new Set(rows.map((row) => row.previewId).filter((id): id is string => id !== null));
  for (const preview of previews) if (!wanted.has(preview)) result.errors.push(`generated/previews/${preview} belongs to no insertable row`);
  if (kitDir === null) result.notes.push('source kit not found: kit comparison and registry hash recomputation skipped');
  return result;
}
