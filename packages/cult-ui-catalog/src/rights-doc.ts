/**
 * The pinned-snapshot block inside docs/legal/cult-ui-pro-rights.md. The importer rewrites it on
 * every import and `--check` fails when it disagrees with catalog.json, so the rights record
 * always names the snapshot the catalog was built from.
 */

import type { SnapshotInfo } from './types.ts';

export const BLOCK_BEGIN = '<!-- cult-snapshot:begin (generated by packages/cult-ui-catalog/scripts/import.ts; do not edit by hand) -->';
export const BLOCK_END = '<!-- cult-snapshot:end -->';

export function renderSnapshotBlock(s: SnapshotInfo): string {
  const state = s.pendingItems === 0 ? 'complete' : `partial: ${s.pendingItems} items still pending fetch`;
  return [
    BLOCK_BEGIN,
    '| Field | Value |',
    '|---|---|',
    `| Snapshot id | \`${s.id}\` |`,
    `| Snapshot digest | \`sha256:${s.digest}\` |`,
    `| Registry index sha256 | \`${s.indexSha256}\` |`,
    `| Items fetched / expected | ${s.fetchedItems} / ${s.expectedItems} (${state}) |`,
    `| Derived section rows | ${s.derivedRows} (sections cut from fetched pages; not registry items) |`,
    BLOCK_END,
  ].join('\n');
}

/** Returns `doc` with its block replaced; throws when the markers are missing. */
export function spliceSnapshotBlock(doc: string, s: SnapshotInfo): string {
  const start = doc.indexOf(BLOCK_BEGIN);
  const end = doc.indexOf(BLOCK_END);
  if (start < 0 || end < start) throw new Error('rights doc has no cult-snapshot block markers');
  return `${doc.slice(0, start)}${renderSnapshotBlock(s)}${doc.slice(end + BLOCK_END.length)}`;
}
