/**
 * The Cult adapter pipeline: the kit → product copy rules (src/converted.ts) and the adapter gate
 * (scripts/adapter-check.ts), run on the committed `generated/` tree without the kit (CI), with
 * a synthetic kit that disagrees, and with the real private kit when this machine has it.
 */

import assert from 'node:assert/strict';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { homedir, tmpdir } from 'node:os';
import { join } from 'node:path';
import { test } from 'node:test';

import {
  checkAdapters,
  foreignCustomProperties,
  PACKAGE_DIR,
  unscopedSelectors,
} from '../scripts/adapter-check.ts';
import {
  ADAPTER_BYTE_LIMIT,
  conversionFields,
  converterSourceSha,
  parseConvertedReport,
  productAdapterSource,
  type ConvertedBlock,
} from '../src/converted.ts';
import type { CultCatalog } from '../src/types.ts';

const catalog = JSON.parse(readFileSync(join(PACKAGE_DIR, 'catalog.json'), 'utf8')) as CultCatalog;
const generatedDir = join(PACKAGE_DIR, 'generated');
const kitDir = process.env.CULT_KIT_DIR ?? join(homedir(), 'projects', 'mm-source-kits', 'cult-ui-pro');
const hasKit = existsSync(join(kitDir, 'converted'));

const KIT_ADAPTER = [
  '// GENERATED by mm-source-kits/cult-ui-pro/scripts/convert.mjs — do not edit by hand.',
  '',
  "import { escapeHtml, type SectionAdapter } from './section-adapter.ts';",
  '',
  'const CSS = ".cult-demo{color:var(--role-foreground)}";',
  '',
  'export const ADAPTER: SectionAdapter = {',
  '  id: "cult-demo",',
  '  version: "1.0.0",',
  '  sourceBlockId: "cult:demo",',
  '  sourceSha256: "' + 'a'.repeat(64) + '",',
  '  roles: ["foreground"],',
  '  text: [{"name":"heading1","max":20}],',
  '  links: [],',
  '  assets: [],',
  '  css: CSS,',
  '  render(fill) {',
  '    const t = fill.text ?? {};',
  '    return `<div class="cult-demo" data-od-role="cta-band"><h2>${escapeHtml(t.heading1 ?? \'\')}</h2></div>`;',
  '  },',
  '};',
  '',
].join('\n');

test('converterSourceSha hashes file contents in path order with no separator', () => {
  const files = [{ path: 'b.tsx', content: 'B' }, { path: 'a.tsx', content: 'A' }];
  // sha256("AB")
  assert.equal(converterSourceSha(files), '38164fbd17603d73f696b8b4d72664d735bb6a7c88577687fd2ae33fd6964153');
});

test('productAdapterSource rewrites only the import path and the id', () => {
  const out = productAdapterSource(KIT_ADAPTER, 'demo');
  assert.ok(out.includes("from '../section-adapter.ts';"));
  assert.ok(out.includes('  id: "cult:demo",'));
  assert.ok(!out.includes('"cult-demo",'));
  const body = (s: string) => s.split('\n').filter((l) => !l.startsWith('//') && !l.startsWith('import') && !l.startsWith('  id:'));
  assert.deepEqual(body(out), body(KIT_ADAPTER));
});

test('productAdapterSource refuses an adapter whose id or source block is not the expected one', () => {
  assert.throws(() => productAdapterSource(KIT_ADAPTER, 'other'), /exactly one id/);
  assert.throws(() => productAdapterSource(KIT_ADAPTER.replace('sourceBlockId: "cult:demo"', 'sourceBlockId: "cult:x"'), 'demo'), /sourceBlockId/);
  assert.throws(() => productAdapterSource(KIT_ADAPTER.replace("'./section-adapter.ts'", "'./elsewhere.ts'"), 'demo'), /import/);
});

test('converter results map to catalog fields; app rows stay app-only and pending rows stay pending', () => {
  const insertable: ConvertedBlock = {
    ...parseConvertedReport({ name: 'demo', status: 'insertable', reasons: [], sizes: { html: { min: 100 }, css: { min: 200 } }, sourceSha256: 'a'.repeat(64) }, 'demo'),
    adapterSource: KIT_ADAPTER,
  };
  const section = { name: 'demo', assetKind: 'section', conversion: { status: 'unconverted' as const } };
  assert.deepEqual(conversionFields(section, insertable), {
    conversion: { status: 'insertable' },
    adapter: { id: 'cult:demo', version: '1.0.0', sourceSha256: 'a'.repeat(64) },
    measuredBytes: { html: 100, css: 200, js: 0 },
    previewId: 'demo.webp',
  });
  const refused: ConvertedBlock = {
    ...parseConvertedReport({ name: 'demo', status: 'adapter-needed', reasons: [{ code: 'oversized', detail: 'x' }, { code: 'canvas/webgl' }] }, 'demo'),
    adapterSource: null,
  };
  assert.deepEqual(conversionFields(section, refused)?.conversion, { status: 'adapter-needed', reason: 'converter refused: oversized, canvas/webgl' });
  assert.equal(conversionFields({ ...section, assetKind: 'app' }, refused), null);
  assert.equal(conversionFields({ ...section, conversion: { status: 'pending-fetch' } }, insertable), null);
  assert.throws(() => parseConvertedReport({ name: 'demo', status: 'insertable', reasons: [] }, 'demo'), /measured/);
  assert.throws(() => parseConvertedReport({ name: 'demo', status: 'adapter-needed', reasons: [] }, 'demo'), /without a reason/);
});

test('CSS scope and custom-property rules', () => {
  const scoped = ':where(.cult-x) :where(h1,h2){margin:0}.cult-x .a{color:var(--role-accent)}@media (min-width:40rem){.cult-x .b{gap:1rem}}@keyframes k{0%{opacity:0}to{opacity:1}}';
  assert.deepEqual(unscopedSelectors(scoped, '.cult-x'), []);
  assert.deepEqual(unscopedSelectors('.cult-xy .a{}h1{}', '.cult-x'), ['.cult-xy .a', 'h1']);
  assert.deepEqual(foreignCustomProperties('.a{--k-a:1;x:var(--k-a);y:var(--k-b,2);z:var(--role-accent)}'), []);
  assert.deepEqual(foreignCustomProperties('.a{x:var(--brand)}'), ['--brand']);
});

test('the committed adapters pass the gate without the kit (CI mode)', async () => {
  const result = await checkAdapters({ catalog, generatedDir, kitDir: null });
  assert.deepEqual(result.errors, []);
  assert.equal(result.kitCompared, false);
  const insertable = catalog.rows.filter((row) => row.conversion.status === 'insertable');
  assert.ok(insertable.length >= 3, 'at least three reviewed Cult blocks are insertable');
  assert.equal(result.measured.length, insertable.length);
  for (const m of result.measured) assert.ok(m.total <= ADAPTER_BYTE_LIMIT, `${m.id} is ${m.total} B`);
  assert.ok(insertable.some((row) => row.id === 'cult:marketing-cta-cosmic'));
});

test('the gate fails when catalog.json and the committed adapter disagree', async () => {
  const mutated = structuredClone(catalog);
  const row = mutated.rows.find((r) => r.id === 'cult:marketing-cta-cosmic')!;
  row.adapter = { ...row.adapter!, version: '9.9.9', sourceSha256: 'b'.repeat(64) };
  const result = await checkAdapters({ catalog: mutated, generatedDir, kitDir: null });
  const committedVersion = catalog.rows.find((r) => r.id === 'cult:marketing-cta-cosmic')!.adapter!.version;
  assert.ok(result.errors.some((e) => e.startsWith(`cult:marketing-cta-cosmic: version ${committedVersion} differs`)), result.errors.join('\n'));
  assert.ok(result.errors.some((e) => e === 'cult:marketing-cta-cosmic: sourceSha256 differs from catalog.json'));

  const dropped = structuredClone(catalog);
  const cta = dropped.rows.find((r) => r.id === 'cult:marketing-cta-cosmic')!;
  Object.assign(cta, { conversion: { status: 'adapter-needed', reason: 'test' }, adapter: null, previewId: null });
  const extra = await checkAdapters({ catalog: dropped, generatedDir, kitDir: null });
  assert.ok(extra.errors.some((e) => e.includes('extra: marketing-cta-cosmic')));
  assert.ok(extra.errors.includes('generated/index.ts is out of date with catalog.json'));
});

test('the gate compares against a kit when one is present, and reports a mismatch', async () => {
  const fakeKit = mkdtempSync(join(tmpdir(), 'cult-fake-kit-'));
  mkdirSync(join(fakeKit, 'converted', 'marketing-cta-cosmic'), { recursive: true });
  mkdirSync(join(fakeKit, 'registry'), { recursive: true });
  writeFileSync(join(fakeKit, 'converted', 'marketing-cta-cosmic', 'adapter.ts'), KIT_ADAPTER);
  writeFileSync(join(fakeKit, 'registry', 'marketing-cta-cosmic.json'), JSON.stringify({ name: 'marketing-cta-cosmic', files: [{ path: 'a.tsx', content: 'changed' }] }));
  const result = await checkAdapters({ catalog, generatedDir, kitDir: fakeKit });
  assert.equal(result.kitCompared, true);
  const cta = result.errors.filter((e) => e.startsWith('cult:marketing-cta-cosmic:'));
  assert.ok(cta.some((e) => /kit adapter cannot be copied|differs from the kit/.test(e)), cta.join('\n'));
  assert.ok(cta.some((e) => e.includes('does not match the pinned registry item')), cta.join('\n'));
  assert.ok(result.errors.some((e) => e.startsWith('cult:marketing-faq-vite: the kit has no converted adapter')));
});

test('with the private kit, every committed adapter equals the kit output and its pinned hash', { skip: hasKit ? false : 'source kit not present' }, async () => {
  const result = await checkAdapters({ catalog, generatedDir, kitDir });
  assert.deepEqual(result.errors, []);
  assert.equal(result.kitCompared, true);
});
