/**
 * Post-`tsc` step for `tsconfig.build.json`. Two jobs, both about the package's checked-in JSON.
 *
 * 1. Copy `src/atlas` and `src/taxonomy` into `dist`. `atlas.ts` and `taxonomy.ts` build
 *    `DEFAULT_ATLAS_PATH`, `DEFAULT_REGISTRY_PATH` and `DEFAULT_TAXONOMY_PATH` from
 *    `import.meta.dirname` and read them with `readFile` rather than an import attribute, so tsc
 *    never sees the JSON and never emits it. Without this copy every default path resolves to a
 *    missing file once a caller imports from `dist` instead of `src`.
 *
 * 2. Emit `dist/data.js` and `dist/data.d.ts`, the same three objects as plain JavaScript
 *    literals. This is what the daemon imports (`@mish/agency-fast-lane/data`).
 *    `import.meta.dirname` is a lie inside a bundle: the packaged mac and Windows daemons are
 *    esbuild prebundles that inline every workspace package, so the module's directory becomes the
 *    prebundle's, where no `atlas/` or `taxonomy/` directory exists — the file loaders would throw
 *    at daemon startup. Data that travels as code survives any bundler on any lane.
 *
 * The three objects are produced by the real loaders, so they are validated (`validateShapeAtlas`,
 * `validateFamilyRegistry`, `validateDesignTaxonomy`) at build time. A malformed data file fails
 * the build instead of every daemon boot.
 *
 * The CLI keeps using the file loaders: it runs from source, where the paths are real, and a
 * developer editing `shape-atlas.json` sees the change without a rebuild.
 */

import { cp, mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { loadAtlasData } from '../src/atlas.ts';
import { loadDesignTaxonomy } from '../src/taxonomy.ts';

const packageRoot = path.resolve(import.meta.dirname, '..');
const distDir = path.join(packageRoot, 'dist');
const DATA_DIRS = ['atlas', 'taxonomy'];

for (const dir of DATA_DIRS) {
  const to = path.join(distDir, dir);
  await mkdir(to, { recursive: true });
  await cp(path.join(packageRoot, 'src', dir), to, { recursive: true });
}

// The bundled word list travels as code (`src/wordlist/scowl-en-us-50.ts`, compiled by tsc); its
// licence text travels next to it.
await mkdir(path.join(distDir, 'wordlist'), { recursive: true });
await cp(path.join(packageRoot, 'src', 'wordlist', 'LICENSE-SCOWL.txt'), path.join(distDir, 'wordlist', 'LICENSE-SCOWL.txt'));

const { atlas, registry } = await loadAtlasData();
const taxonomy = await loadDesignTaxonomy();

const banner = '// Generated by scripts/copy-dist-data.ts from the package\'s checked-in JSON. Do not edit.\n';

await writeFile(
  path.join(distDir, 'data.js'),
  `${banner}export const shapeAtlas = ${JSON.stringify(atlas)};\n`
  + `export const familyRegistry = ${JSON.stringify(registry)};\n`
  + `export const designTaxonomy = ${JSON.stringify(taxonomy)};\n`,
);

await writeFile(
  path.join(distDir, 'data.d.ts'),
  `${banner}import type { FamilyRegistry, ShapeAtlas } from './atlas.js';\n`
  + `import type { DesignTaxonomy } from './taxonomy.js';\n`
  + `export declare const shapeAtlas: ShapeAtlas;\n`
  + `export declare const familyRegistry: FamilyRegistry;\n`
  + `export declare const designTaxonomy: DesignTaxonomy;\n`,
);
