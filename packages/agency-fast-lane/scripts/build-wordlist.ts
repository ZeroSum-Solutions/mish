/**
 * Regenerates `src/wordlist/scowl-en-us-50.ts` from an ESDB/SCOWL word list download.
 *
 *   curl -sL -o scowl50.txt 'http://app.aspell.net/create?max_size=50&spelling=US&max_variant=0&diacritic=strip&special=hacker&download=wordlist&encoding=utf-8&format=inline'
 *   node --experimental-strip-types scripts/build-wordlist.ts scowl50.txt
 *
 * Keeps lowercase letter-only entries (no proper nouns, no possessives), sorted and unique, and
 * writes them gzip-compressed and base64-encoded as code, so the list survives the daemon's
 * esbuild prebundle (no file read relative to `import.meta.dirname`). The copyright header of the
 * download is kept in `src/wordlist/LICENSE-SCOWL.txt`.
 */

import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { gzipSync } from 'node:zlib';

const source = process.argv[2];
if (!source) throw new Error('usage: build-wordlist.ts <scowl-download.txt>');
const text = await readFile(source, 'utf8');
const divider = text.indexOf('\n---\n');
if (divider < 0) throw new Error('not an ESDB download: no --- divider after the header');
const header = text.slice(0, divider);
const revision = /ESDB Git Revision: (.+)/.exec(header)?.[1]?.trim() ?? 'unknown';
const params = ['Size', 'Spelling', 'Variant Level', 'Special', 'Diacritics'].map((key) => `${key.toLowerCase()} ${new RegExp(`${key}: (.+)`).exec(header)?.[1]?.replace(/\*default\*/, '').trim() ?? '?'}`).join(', ');
const words = [...new Set(text.slice(divider + 5).split('\n').map((line) => line.trim()).filter((line) => /^[a-z]+$/.test(line)))].sort();
const encoded = gzipSync(Buffer.from(words.join('\n'), 'utf8'), { level: 9 }).toString('base64');
const chunks = encoded.match(/.{1,1000}/g) ?? [];
const out = path.resolve(import.meta.dirname, '../src/wordlist');
await writeFile(path.join(out, 'scowl-en-us-50.ts'), [
  '// GENERATED by scripts/build-wordlist.ts — do not edit.',
  '// Source: ESDB (SCOWL) custom list from https://app.aspell.net/create',
  `// (${params}); ESDB revision ${revision}.`,
  `// ${words.length} lowercase words, gzip + base64. Licence: src/wordlist/LICENSE-SCOWL.txt (Kevin Atkinson, permissive).`,
  `export const SCOWL_EN_US_50_WORDS = ${words.length};`,
  `export const SCOWL_EN_US_50_REVISION = ${JSON.stringify(revision)};`,
  'export const SCOWL_EN_US_50_GZIP_BASE64 = [',
  ...chunks.map((chunk) => `  '${chunk}',`),
  "].join('');",
  '',
].join('\n'));
await writeFile(path.join(out, 'LICENSE-SCOWL.txt'), `${header.trim()}\n`);
console.log(`${words.length} words, ${encoded.length} base64 bytes, revision ${revision}`);
