import { createHash } from 'node:crypto';
import { canonicalJson } from '../../placement/adoption-plan.js';
import { REACT95_KIT } from '../../kits/react95/kit.generated.js';
import { REACT95_TOOLCHAIN } from '../../kits/react95/pins.js';
import { react95UnitFiles } from '../../kits/react95/unit.js';
import type { ReactReceiptCheck } from './receipt.js';

/**
 * G02 receipt for the React95 kit's `react-source/v1` units (same
 * `g02-react-receipt/1` mechanism as the GSAP receipt, its own source and
 * toolchain). Generated deterministically by
 * `tests/workbench/g02-react95-receipt-build.ts`: each template unit is
 * type-checked under the recorded project profile, built in production mode,
 * rendered on the server without a window, hydrated under Strict Mode, and
 * driven through its behavior, keyboard, style-isolation, contrast and cleanup
 * checks. Evidence copy:
 * `docs/plans/2026-10-02-design-workbench/evidence/implementation-start/g02-react95-receipt.json`.
 */
export interface React95CheckResult { name: string; passed: boolean; detail: string }
export interface React95TemplateReceipt {
  template: string;
  /** Digest of the exact unit file list apply writes (paths, roles, SHA-256). */
  unitSha256: string;
  files: { path: string; sha256: string }[];
  typecheck: { diagnostics: number };
  outputs: { productionBundle: { sha256: string; bytes: number }; preview: { sha256: string; bytes: number } };
  checks: React95CheckResult[];
}
export interface React95KitReceipt {
  schema: 'g02-react-receipt/1';
  adapter: 'react-source/v1';
  sources: ['react95'];
  status: 'passed' | 'failed';
  toolchainResolution: string;
  toolchain: Record<keyof typeof REACT95_TOOLCHAIN, string>;
  source: { repository: string; commit: string; archiveSha256: string };
  fixture: { path: string; files: { path: string; sha256: string }[] };
  typecheckProfile: Record<string, unknown>;
  build: { tool: 'esbuild'; options: Record<string, unknown>; inputs: { path: string; sha256: string }[]; generator: string };
  /** Packages the preview document bundles, with the licence evidence their published bytes carry. */
  bundledPackages: { name: string; version: string; manifestLicense: string | null; licenceFile: { path: string; sha256: string } | null }[];
  templates: React95TemplateReceipt[];
  /**
   * Real-browser layer: both receipt-hashed preview documents rendered by the
   * daemon's CDP review worker in headless Chromium at each PRD width, with
   * overflow, 44px pointer targets, keyboard order/focus visibility and
   * console/resource checks. Generated by `runReact95BrowserChecks`; bound to
   * each preview by its SHA-256.
   */
  browser?: React95BrowserReceipt;
}
export const REACT95_BROWSER_WIDTHS = [320, 375, 768, 1440] as const;
export const REACT95_BROWSER_CHECKS = [
  'no horizontal overflow', 'every interactive target is at least 44px',
  'keyboard order follows the document with a visible focus at every stop', 'no console errors and every resource served',
] as const;
export interface React95BrowserReceipt {
  worker: 'cdp-review/headless';
  widths: number[];
  templates: { template: string; previewSha256: string; checks: React95CheckResult[] }[];
}

/** Every template has passing browser results at every width, bound to its exact preview document. */
function browserCovers(browser: unknown, templates: readonly Partial<React95TemplateReceipt>[]): boolean {
  if (!isObject(browser) || browser.worker !== 'cdp-review/headless' || !Array.isArray(browser.templates)
    || JSON.stringify(browser.widths) !== JSON.stringify(REACT95_BROWSER_WIDTHS)) return false;
  const entries = browser.templates as Partial<React95BrowserReceipt['templates'][number]>[];
  return templates.every(template => {
    const entry = entries.find(candidate => candidate.template === template.template);
    if (!entry || entry.previewSha256 !== template.outputs?.preview.sha256 || !Array.isArray(entry.checks) || entry.checks.some(check => check?.passed !== true)) return false;
    return REACT95_BROWSER_WIDTHS.every(width => REACT95_BROWSER_CHECKS.every(kind => entry.checks!.some(check => check.name === `browser:${width}:${kind}`)));
  });
}

const sha256 = (bytes: Buffer | string) => createHash('sha256').update(bytes).digest('hex');
const isObject = (value: unknown): value is Record<string, unknown> => !!value && typeof value === 'object' && !Array.isArray(value);

/** The unit digest the receipt must name: path, role and SHA-256 of every file apply writes. */
export function react95UnitDigest(templateId: string): string | null {
  const files = react95UnitFiles(REACT95_KIT, templateId);
  return files ? sha256(canonicalJson(files.map(file => ({ path: file.path, role: file.role, sha256: sha256(file.bytes) })))) : null;
}
export function currentReact95Units(): { template: string; sha256: string }[] {
  return REACT95_KIT.templates.map(template => ({ template: template.id, sha256: react95UnitDigest(template.id)! }));
}

/**
 * Validates a React95 receipt against the current pins, kit source and exact
 * unit bytes. A template is covered only when every one of its recorded checks
 * passed; a stale unit, a different pin or a failed check keeps the gate shut.
 */
export function validateReact95Receipt(receipt: unknown, expected: readonly { template: string; sha256: string }[] = currentReact95Units()): ReactReceiptCheck {
  if (receipt === null || receipt === undefined) return { ok: false, reason: 'receipt-missing' };
  if (!isObject(receipt) || receipt.schema !== 'g02-react-receipt/1' || receipt.adapter !== 'react-source/v1' || !Array.isArray(receipt.sources)
    || receipt.sources.length !== 1 || receipt.sources[0] !== 'react95' || !isObject(receipt.toolchain) || !isObject(receipt.source)
    || !Array.isArray(receipt.templates) || typeof receipt.toolchainResolution !== 'string' || !receipt.toolchainResolution) return { ok: false, reason: 'receipt-invalid' };
  const templates = receipt.templates as Partial<React95TemplateReceipt>[];
  if (receipt.status !== 'passed' || templates.some(entry => !Array.isArray(entry.checks) || entry.checks.length === 0 || entry.checks.some(check => check?.passed !== true)
    || entry.typecheck?.diagnostics !== 0) || !browserCovers(receipt.browser, templates)) return { ok: false, reason: 'receipt-failed' };
  const toolchain = receipt.toolchain as Record<string, unknown>;
  const source = receipt.source as Record<string, unknown>;
  if (Object.entries(REACT95_TOOLCHAIN).some(([name, version]) => toolchain[name] !== version)
    || source.commit !== REACT95_KIT.source.commit || source.archiveSha256 !== REACT95_KIT.source.archive.sha256) return { ok: false, reason: 'receipt-toolchain-mismatch' };
  const recorded = new Map(templates.map(entry => [entry.template, entry.unitSha256]));
  if (expected.length === 0 || expected.some(unit => recorded.get(unit.template) !== unit.sha256)) return { ok: false, reason: 'receipt-unit-mismatch' };
  return { ok: true };
}
