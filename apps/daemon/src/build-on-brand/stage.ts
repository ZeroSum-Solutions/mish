/**
 * What the daemon stages into a Build on brand project before the run, and the host-authored
 * first message that starts it (spec §"Stage" and §"Run"). Pure: every function returns text.
 *
 * The run message carries the brief, the kit, the plan and (when there is one) the structure
 * digest. It never carries the reference URL, so the agent cannot fetch the page and copy it.
 * No system-prompt text changes here: the message and the staged files reach the legacy, BYOK
 * and OD Next composition paths identically (docs/prompt-composition.md).
 */
import type { BuildOnBrandPlan, BuildOnBrandRoute } from '@open-design/contracts';

export const STAGE_DIR = '_brand-build';

export interface StagedInsert {
  /** The plan section's `ref` (a catalogue entry id). */
  ref: string;
  /** File stem under `_brand-build/inserts/`. */
  file: string;
  html: string;
  css: string;
  slots: Array<{ name: string; max: number }>;
}

export interface StageInput {
  brief: string;
  plan: BuildOnBrandPlan;
  kitTitle?: string;
  /** The kit's `tokens.css`, copied to the project root as-is. */
  tokensCss: string;
  inserts: StagedInsert[];
  warnings: string[];
  /** Ids only; see `BuildOnBrandRoute`. */
  route?: BuildOnBrandRoute;
}

/** `cult:pricing-series-v` → `cult-pricing-series-v`. */
export function insertFileStem(ref: string): string {
  return ref.toLowerCase().replace(/[^a-z0-9]+/gu, '-').replace(/^-+|-+$/gu, '').slice(0, 80) || 'insert';
}

/** Custom property names a stylesheet declares, in order of first appearance. */
export function declaredTokenNames(css: string): string[] {
  const names: string[] = [];
  for (const match of css.matchAll(/(--[A-Za-z0-9_-]+)\s*:/gu)) {
    const name = match[1]!;
    if (!names.includes(name)) names.push(name);
  }
  return names;
}

// Each role lists a hand-written kit's names first, then the `--brand-*` names the brand importer
// writes to `system/variables.css` (brands/engine/export.ts), which stands in for tokens.css on an
// imported or pasted kit. The first declared candidate wins.
const ROLE_MAP: Array<[string, string[], string]> = [
  ['--role-background', ['--bg', '--background', '--color-bg', '--brand-color-bg-container'], '#ffffff'],
  ['--role-surface', ['--surface', '--card', '--color-surface', '--brand-color-bg-elevated', '--brand-color-bg-layout'], '#f6f6f6'],
  ['--role-foreground', ['--fg', '--foreground', '--text', '--color-fg', '--brand-color-text'], '#111111'],
  ['--role-muted', ['--muted', '--fg-2', '--muted-foreground', '--brand-color-text-secondary'], '#555555'],
  ['--role-accent', ['--accent', '--primary', '--brand', '--brand-color-primary'], '#1e5a78'],
  ['--role-on-accent', ['--accent-on', '--on-accent', '--primary-foreground', '--brand-color-text-light-solid'], '#ffffff'],
  ['--role-border', ['--border', '--border-soft', '--line', '--brand-color-border'], '#dddddd'],
  ['--role-font-display', ['--font-display', '--font-heading', '--font-sans', '--brand-font-family'], 'system-ui, sans-serif'],
  ['--role-font-body', ['--font-body', '--font-sans', '--font-text', '--brand-font-family'], 'system-ui, sans-serif'],
  ['--role-font-mono', ['--font-mono', '--brand-font-family-code'], 'ui-monospace, monospace'],
];

/** `--role-*` (what catalogue inserts read) mapped onto the kit's own custom properties. */
export function rolesCss(tokensCss: string): string {
  const declared = new Set(declaredTokenNames(tokensCss));
  const lines = ROLE_MAP.map(([role, candidates, fallback]) => {
    const chosen = candidates.filter((name) => declared.has(name));
    const value = chosen.length > 0 ? chosen.reduceRight((inner, name) => `var(${name}, ${inner})`, fallback) : fallback;
    return `  ${role}: ${value};`;
  });
  return `/* Generated by Build on brand: maps the catalogue's --role-* properties onto this kit's tokens. Link after tokens.css. */\n:root {\n${lines.join('\n')}\n}\n`;
}

