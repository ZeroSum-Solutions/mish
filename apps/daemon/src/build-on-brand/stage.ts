function sectionLine(section: BuildOnBrandPlan['pages'][number]['sections'][number], inserts: Map<string, StagedInsert>): string {
  if (section.source === 'catalog' && section.ref) {
    const insert = inserts.get(section.ref);
    if (insert) {
      return `${section.role} — catalogue insert \`${section.ref}\`: markup \`${STAGE_DIR}/inserts/${insert.file}.html\`, styles \`${STAGE_DIR}/inserts/${insert.file}.css\``;
    }
  }
  if (section.source === 'library' && section.ref) return `${section.role} — library insert \`${section.ref}\``;
  return `${section.role} — built from the kit's own components`;
}

export function planOutline(plan: BuildOnBrandPlan, inserts: StagedInsert[]): string {
  const byRef = new Map(inserts.map((insert) => [insert.ref, insert]));
  return plan.pages
    .map((page, index) => {
      const sections = page.sections.map((section) => `   - ${sectionLine(section, byRef)}`).join('\n');
      return `${index + 1}. \`${page.file}\` (${page.role})\n${sections}`;
    })
    .join('\n');
}

export function rulesText(plan: BuildOnBrandPlan): string {
  const files = plan.pages.map((page) => `\`${page.file}\``).join(', ');
  return [
    `- Write exactly these ${plan.pages.length} pages as root-level files: ${files}. \`index.html\` is the home page. Write every one of them in this turn; do not stop after the first page.`,
    '- Every page starts with `<!doctype html>`, sets `<meta name="viewport" content="width=device-width, initial-scale=1">`, and links, in this order: `tokens.css`, `_brand-build/roles.css`, `_brand-build/base.css`, then one shared `site.css` you write for the layout.',
    `- Every page has the same header with \`<nav aria-label="Primary">\` linking all pages by relative file name (${files}), and the same footer. Every local link must open a page that exists.`,
    `- Use the kit "${plan.designSystem.id}": colours, fonts, radii, shadows and spacing come from the custom properties in \`tokens.css\` (use \`var(--…)\`). Do not write literal colour values outside \`tokens.css\`. Prefer the kit's component classes and patterns from its DESIGN.md.`,
    '- Catalogue inserts: copy the markup from the named file into the page, link or inline its CSS once, and replace every `{{slot}}` with copy written for this brief that fits the length given in BUILD.md.',
    '- Images: no remote images and no image generation of any kind. Where a photo belongs, use a labelled stand-in: `<div class="od-stand-in" role="img" aria-label="Stand-in image: <what the photo shows>"></div>`. The stand-ins are part of the delivered draft; do not leave TODOs about them.',
    '- Copy: write it from the brief. Where a fact is missing (address, phone number, prices, names), write a clearly marked placeholder such as "[Phone number]"; never invent credentials or reviews from real people.',
    '- Responsive: mobile first; the layout works at 375px and 1440px wide with no horizontal scrolling.',
    '- Motion: keep it subtle. Every animation and transition must stop under `prefers-reduced-motion: reduce` (base.css resets it; do not override that).',
    '- Accessibility: one `<h1>` per page, landmarks (`header`, `nav`, `main`, `footer`), visible focus styles, and text contrast that meets WCAG AA on the kit colours.',
    '- This run is unattended: do not ask questions and do not emit `<question-form>`. Make reasonable choices from the brief and finish the site.',
  ].join('\n');
}

function warningNotes(warnings: readonly string[]): string {
  return warnings.length > 0 ? `\n## Plan notes\n${warnings.slice(0, 20).map((warning) => `- ${warning}`).join('\n')}\n` : '';
}

function routeNotes(route: BuildOnBrandRoute | undefined): string {
  if (!route) return '';
  const lines: string[] = [];
  if (route.spine) lines.push(`- Industry spine: ${route.spine}`);
  if (route.family) lines.push(`- Site family: ${route.family}`);
  for (const [id, choice] of Object.entries(route.sections ?? {})) lines.push(`- Family section ${id}: ${choice}`);
  return lines.length > 0 ? `\n## Route (from the Design Index)\n${lines.join('\n')}\n` : '';
}

export function buildMd(input: StageInput): string {
  const insertDetails = input.inserts
    .map((insert) => {
      const slots = insert.slots.map((slot) => `\`{{${slot.name}}}\` ≤ ${slot.max} chars`).join(', ');
      return `- \`${insert.ref}\` → \`inserts/${insert.file}.html\` + \`inserts/${insert.file}.css\`${slots ? `. Slots: ${slots}` : ''}`;
    })
    .join('\n');
  const checklist = input.plan.pages.map((page) => `- [ ] \`${page.file}\` written and linked from every page's nav`).join('\n');
  return `# Build on brand — first draft

## Brief
${input.brief.trim() || '(No brief text: build from the plan and the reference structure.)'}

## Kit
${input.plan.designSystem.id}${input.kitTitle ? ` — ${input.kitTitle}` : ''}. Tokens: \`tokens.css\` (project root). Role map: \`roles.css\`. Base, stand-ins and reduced motion: \`base.css\`.
${routeNotes(input.route)}${warningNotes(input.warnings)}
## Pages and sections
${planOutline(input.plan, input.inserts)}

## Inserts
${insertDetails || '- None. Every section is built from the kit.'}

## Rules
${rulesText(input.plan)}

## Checklist
${checklist}
- [ ] Every page links tokens.css, roles.css and base.css
- [ ] Every image slot is a labelled \`.od-stand-in\`
- [ ] No remote images, no lorem ipsum
`;
}

export function noticeMd(inserts: StagedInsert[]): string {
  const lines = inserts.map((insert) => `- \`${insert.ref}\`: rendered from the bundled section catalogue adapter, with text slots left as \`{{slot}}\` placeholders.`);
  return `# Provenance\n\nThe inserts in this folder come from the Mishh Mashh section catalogue (insertable adapters only).\n\n${lines.join('\n') || '- No inserts.'}\n`;
}

/** Every file to write into the project, keyed by project-relative path. */
export function stagedFiles(input: StageInput): Record<string, string> {
  const files: Record<string, string> = {
    'tokens.css': input.tokensCss,
    [`${STAGE_DIR}/plan.json`]: `${JSON.stringify(input.plan, null, 2)}\n`,
    [`${STAGE_DIR}/BUILD.md`]: buildMd(input),
    [`${STAGE_DIR}/roles.css`]: rolesCss(input.tokensCss),
    [`${STAGE_DIR}/base.css`]: BASE_CSS,
    [`${STAGE_DIR}/NOTICE.md`]: noticeMd(input.inserts),
  };
  for (const insert of input.inserts) {
    files[`${STAGE_DIR}/inserts/${insert.file}.html`] = `${insert.html}\n`;
    files[`${STAGE_DIR}/inserts/${insert.file}.css`] = `${insert.css}\n`;
  }
  return files;
}

/**
 * The host-authored first message of the run. It inlines everything the agent needs so the
 * build does not depend on the agent reading BUILD.md first; BUILD.md repeats it as a checklist.
 */
export function runMessage(input: StageInput): string {
  const tokens = declaredTokenNames(input.tokensCss).slice(0, 60);
  const digest = input.plan.reference?.digest;
  return `Build a ${input.plan.pages.length}-page client website, a working first draft, on the design kit "${input.plan.designSystem.id}"${input.kitTitle ? ` (${input.kitTitle})` : ''}.

## Brief
${input.brief.trim() || '(No brief text: build from the plan and the reference structure below.)'}
${routeNotes(input.route)}
## Kit binding
- The daemon copied the kit's \`tokens.css\` into the project root. Its custom properties: ${tokens.map((name) => `\`${name}\``).join(', ') || '(none found)'}.
- \`${STAGE_DIR}/roles.css\` maps the catalogue's \`--role-*\` properties onto those tokens; \`${STAGE_DIR}/base.css\` holds the reset, the \`.od-stand-in\` style and the reduced-motion rule.

${warningNotes(input.warnings)}
## Pages and sections
${planOutline(input.plan, input.inserts)}
${digest ? `\n## Reference structure (structure only: roles and layouts, no copy)\n\`\`\`json\n${JSON.stringify(digest, null, 2)}\n\`\`\`\nFollow its section order and layouts where they fit the brief. It holds no text, images or links to reuse.\n` : ''}
## Rules
${rulesText(input.plan)}

The full plan is in \`${STAGE_DIR}/plan.json\` and the checklist in \`${STAGE_DIR}/BUILD.md\`. When every page is written, reply with the list of files you wrote.
`;
}
