import { createHash, randomUUID } from 'node:crypto';
import { mkdir, mkdtemp, open, rm, stat, symlink, utimes, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { afterEach, describe, expect, it } from 'vitest';

import { closeDatabase, insertProject, openDatabase } from '../../src/db.js';
import { createGalleryOutputMatcher } from '../../src/media/gallery-witness.js';
import {
  MEDIA_IDEMPOTENCY_TTL_MS,
  findMediaLineageByIdempotencyKey,
  recordMediaTaskLineage,
} from '../../src/media/lineage.js';
import { redactMediaErrorText } from '../../src/media/redact.js';
import { LEAKED_SECRETS, LEAKY_PROVIDER_MESSAGE } from './r10-harness.js';

const dirs: string[] = [];
afterEach(async () => {
  closeDatabase();
  for (const dir of dirs.splice(0)) await rm(dir, { recursive: true, force: true });
});
async function scratchDir(prefix: string): Promise<string> {
  const dir = await mkdtemp(path.join(tmpdir(), prefix));
  dirs.push(dir);
  return dir;
}
const sha = (bytes: Buffer) => createHash('sha256').update(bytes).digest('hex');

describe('B1 redactMediaErrorText', () => {
  it('keeps origin and path, drops userinfo, query, fragment and token-shaped strings', () => {
    const redacted = redactMediaErrorText(LEAKY_PROVIDER_MESSAGE);
    for (const secret of LEAKED_SECRETS) expect(redacted).not.toContain(secret);
    expect(redacted).toContain('https://cdn.fake-provider.test/out/image.png');
    expect(redacted).toContain('Bearer [REDACTED]');
  });

  it('redacts JWTs, AWS key ids and key=value credentials, and leaves ordinary text alone', () => {
    expect(redactMediaErrorText('token eyJhbGciOi.eyJzdWIiOiIxIn0.c2lnbmF0dXJl done')).not.toContain('eyJzdWIiOiIxIn0');
    expect(redactMediaErrorText('id AKIAABCDEFGHIJKLMNOP')).not.toContain('AKIAABCDEFGHIJKLMNOP');
    expect(redactMediaErrorText('access_token: abc123def; password=hunter2')).not.toMatch(/abc123def|hunter2/);
    const plain = 'openai image 429: rate limited, retry after 20s (hero.png)';
    expect(redactMediaErrorText(plain)).toBe(plain);
  });
});

describe('W2/Q4 gallery output matcher', () => {
  it('charges every hashed byte to the budget and refuses to read past it', async () => {
    const projectDir = await scratchDir('r10-budget-');
    const bytes = Buffer.alloc(1000, 7);
    for (const name of ['a.png', 'b.png', 'c.png']) await writeFile(path.join(projectDir, name), bytes);
    const matcher = createGalleryOutputMatcher({ projectDir, budgetBytes: 2500, cache: new Map() });
    const record = { size: 1000, sha256: sha(bytes) };
    expect(await matcher.matches(path.join(projectDir, 'a.png'), record)).toBe('match');
    expect(await matcher.matches(path.join(projectDir, 'b.png'), record)).toBe('match');
    expect(matcher.spentBytes()).toBe(2000);
    // The third would exceed the budget: not read, not a mismatch.
    expect(await matcher.matches(path.join(projectDir, 'c.png'), record)).toBe('unreadable');
    expect(matcher.spentBytes()).toBe(2000);
  });

  it('serves an unchanged file from the verdict cache without charging again, and re-reads a changed one', async () => {
    const projectDir = await scratchDir('r10-cache-');
    const bytes = Buffer.from('cached bytes');
    const file = path.join(projectDir, 'x.png');
    await writeFile(file, bytes);
    const cache = new Map<string, 'match' | 'mismatch'>();
    const record = { size: bytes.length, sha256: sha(bytes) };
    const first = createGalleryOutputMatcher({ projectDir, budgetBytes: 1_000, cache });
    expect(await first.matches(file, record)).toBe('match');
    const second = createGalleryOutputMatcher({ projectDir, budgetBytes: 1_000, cache });
    expect(await second.matches(file, record)).toBe('match');
    expect(second.spentBytes()).toBe(0);

    await writeFile(file, Buffer.from('other bytes!'));
    const third = createGalleryOutputMatcher({ projectDir, budgetBytes: 1_000, cache });
    expect(await third.matches(file, record)).toBe('mismatch');
  });

  it('Sol B5/6 WARN: a same-size in-place edit with its mtime restored is not served as the generated output', async () => {
    const projectDir = await scratchDir('r10-ctime-');
    const bytes = Buffer.from('generated bytes');
    const file = path.join(projectDir, 'x.png');
    await writeFile(file, bytes);
    const stamp = new Date(1_700_000_000_000);
    await utimes(file, stamp, stamp);
    const cache = new Map<string, 'match' | 'mismatch'>();
    const record = { size: bytes.length, sha256: sha(bytes) };
    expect(await createGalleryOutputMatcher({ projectDir, budgetBytes: 1_000, cache }).matches(file, record)).toBe('match');
    const before = await stat(file);
    await new Promise(done => setTimeout(done, 20));
    // Same size, different bytes, written in place (same inode), then the mtime is put back.
    const handle = await open(file, 'r+');
    try { await handle.write(Buffer.from('REPLACED bytes!'), 0, bytes.length, 0); } finally { await handle.close(); }
    await utimes(file, stamp, stamp);
    const after = await stat(file);
    expect([after.ino, after.size, after.mtimeMs]).toEqual([before.ino, before.size, before.mtimeMs]);
    expect(await createGalleryOutputMatcher({ projectDir, budgetBytes: 1_000, cache }).matches(file, record)).toBe('mismatch');
  });

  it('refuses a path whose parent directory resolves outside the project', async () => {
    const projectDir = await scratchDir('r10-contain-');
    const outside = await scratchDir('r10-contain-out-');
    const bytes = Buffer.from('escaped');
    await writeFile(path.join(outside, 'pic.png'), bytes);
    await symlink(outside, path.join(projectDir, 'linked'));
    await mkdir(path.join(projectDir, 'real'));
    await writeFile(path.join(projectDir, 'real', 'pic.png'), bytes);
    const matcher = createGalleryOutputMatcher({ projectDir, budgetBytes: 1_000, cache: new Map() });
    const record = { size: bytes.length, sha256: sha(bytes) };
    expect(await matcher.matches(path.join(projectDir, 'linked', 'pic.png'), record)).toBe('mismatch');
    expect(await matcher.matches(path.join(projectDir, 'real', 'pic.png'), record)).toBe('match');
  });
});

describe('NIT idempotency keys are scoped per project and principal, and expire', () => {
  it('lets two principals use the same key independently and frees a key after the TTL', async () => {
    const dataDir = await scratchDir('r10-idem-');
    const db = openDatabase(process.cwd(), { dataDir });
    const now = Date.now();
    insertProject(db, { id: 'p1', name: 'p1', createdAt: now, updatedAt: now });
    const record = (taskId: string, principal: string, createdAt: number) => recordMediaTaskLineage(db, {
      taskId,
      projectId: 'p1',
      status: 'queued',
      createdAt,
      request: null,
      idempotencyKey: 'shared-key',
      idempotencyPrincipal: principal,
    });
    record('t-alice', 'member-alice', now);
    record('t-bob', 'member-bob', now);
    expect(findMediaLineageByIdempotencyKey(db, 'p1', 'member-alice', 'shared-key', now)?.taskId).toBe('t-alice');
    expect(findMediaLineageByIdempotencyKey(db, 'p1', 'member-bob', 'shared-key', now)?.taskId).toBe('t-bob');

    const later = now + MEDIA_IDEMPOTENCY_TTL_MS + 1;
    expect(findMediaLineageByIdempotencyKey(db, 'p1', 'member-alice', 'shared-key', later)).toBeNull();
    // An expired key is free again.
    expect(() => record(`t-${randomUUID()}`, 'member-alice', later)).not.toThrow();
  });
});
