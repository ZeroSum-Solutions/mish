/**
 * Pure readings of a media gallery entry. The row component only draws what
 * these return, so the rules that matter (a cancel is not a failure, a safety
 * refusal never offers Retry, a stub never passes for a generated asset, a
 * superseded output offers nothing to download) live in one testable place.
 */
import {
  mediaSafetyCategory,
  type MediaFailureNextStep,
  type MediaGalleryEntry,
  type MediaSafetyCategory,
} from '@mish/contracts';

export type MediaEntryStatusView =
  | 'queued'
  | 'running'
  | 'done'
  | 'failed'
  | 'cancelled'
  | 'restart-interrupted'
  | 'interrupted';

export type MediaEntryTone = 'neutral' | 'info' | 'success' | 'warning' | 'danger';

export interface MediaEntryView {
  status: MediaEntryStatusView;
  tone: MediaEntryTone;
  /** A content-safety refusal's category, when this entry is one. */
  safetyCategory?: MediaSafetyCategory;
  /** The failure's next step, for a real failure only (never a user cancel). */
  nextStep?: MediaFailureNextStep;
  canCancel: boolean;
  canRetry: boolean;
  /** A file the user can download or reuse: real generated bytes, verified where we say (`current` or `moved`). */
  usableFile: boolean;
  stub: boolean;
}

const TONE: Record<MediaEntryStatusView, MediaEntryTone> = {
  queued: 'neutral',
  running: 'info',
  done: 'success',
  failed: 'danger',
  cancelled: 'neutral',
  'restart-interrupted': 'warning',
  interrupted: 'warning',
};

export function isActiveMediaEntry(entry: MediaGalleryEntry): boolean {
  return entry.status === 'queued' || entry.status === 'running';
}

export function mediaEntryView(entry: MediaGalleryEntry): MediaEntryView {
  const status: MediaEntryStatusView = entry.status === 'interrupted'
    ? entry.interruptReason === 'user-cancelled'
      ? 'cancelled'
      : entry.interruptReason === 'daemon-restart' ? 'restart-interrupted' : 'interrupted'
    : entry.status;
  const safetyCategory = entry.provenance.safetyCategory
    ?? mediaSafetyCategory(entry.error?.code, entry.error?.category);
  const terminalFailure = entry.status === 'failed' || entry.status === 'interrupted';
  // Placeholder bytes are never handed out as an asset: a stub is shown and
  // labelled, but it cannot be downloaded or copied into another project.
  // Only a verified output (`current`, or `moved` and found by its digest) is
  // an asset; an `unverifiable` one keeps its preview and warning, but its
  // bytes are unproven (and reuse would be refused without a digest).
  const usableFile = Boolean(entry.file)
    && !entry.provenance.stub
    && (entry.output.state === 'current' || entry.output.state === 'moved');
  return {
    status,
    tone: TONE[status],
    ...(safetyCategory ? { safetyCategory } : {}),
    ...(status === 'failed' && entry.error?.nextStep ? { nextStep: entry.error.nextStep } : {}),
    canCancel: isActiveMediaEntry(entry),
    // A safety refusal repeated unchanged is refused again; the daemon answers
    // 422 for it, so the button would only ever produce an error.
    canRetry: terminalFailure && entry.replayable && !safetyCategory,
    usableFile,
    stub: entry.provenance.stub,
  };
}

/** The last path segment, used as a download name. */
export function mediaFileBaseName(name: string): string {
  const parts = name.split('/');
  return parts[parts.length - 1] || name;
}

/** Local calendar day `yyyy-mm-dd` → epoch ms at its local midnight, or undefined. */
export function localDayStart(value: string): number | undefined {
  const match = /^(\d{4})-(\d{2})-(\d{2})$/.exec(value);
  if (!match) return undefined;
  const time = new Date(Number(match[1]), Number(match[2]) - 1, Number(match[3])).getTime();
  return Number.isFinite(time) ? time : undefined;
}

/** The exclusive upper bound that includes the whole chosen local day. */
export function localDayEndExclusive(value: string): number | undefined {
  const match = /^(\d{4})-(\d{2})-(\d{2})$/.exec(value);
  if (!match) return undefined;
  const time = new Date(Number(match[1]), Number(match[2]) - 1, Number(match[3]) + 1).getTime();
  return Number.isFinite(time) ? time : undefined;
}
